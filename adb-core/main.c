static inline void pool_aggregates_range_pools(target_half_t half, int from, int to,
                                               int *current, int *busy, int *near_full, int *free_slots) {
    worker_t *pool = (half == TARGET_LOWER_HALF) ? workers_lower : workers_upper;
    int limit = (half == TARGET_LOWER_HALF)
              ? atomic_load(&worker_count_lower)
              : atomic_load(&worker_count_upper);

    int cur=0, bz=0, nf=0, fs=0;

    if (!pool) {
        if (current) *current = cur;
        if (busy) *busy = bz;
        if (near_full) *near_full = nf;
        if (free_slots) *free_slots = fs;
        return;
    }

    if (from < 0) from = 0;
    if (to > limit) to = limit;

    for (int i = from; i < to; ++i) {
        worker_t *w = &pool[i];
        if (w->epoll_fd <= 0 || w->clients == NULL || atomic_load(&w->is_quarantined)) continue;
        cur++;
        if (atomic_load(&w->active_tasks) > 0) bz++;
        if (w->num_clients >= (INITIAL_CLIENT_CAPACITY * 9) / 10) nf++; // «почти полон» ~90%
        fs += (INITIAL_CLIENT_CAPACITY - w->num_clients);
    }

    if (current) *current = cur;
    if (busy) *busy = bz;
    if (near_full) *near_full = nf;
    if (free_slots) *free_slots= fs;
}

static inline int pressure_score_half_pools(target_half_t half) {
    int cnt = (half == TARGET_LOWER_HALF)
            ? atomic_load(&worker_count_lower)
            : atomic_load(&worker_count_upper);

    int from = 0;
    int to = cnt;

    int current=0, busy=0, near_full=0, free_slots=0;
    pool_aggregates_range_pools(half, from, to, &current, &busy, &near_full, &free_slots);
    if (current <= 0) return 0;

    int busy_ppm = (busy * 1000) / current; // 0..1000
    int deficit = (current * INITIAL_CLIENT_CAPACITY) / 8 - free_slots; // ориентир «1/8 пула» как запас
    if (deficit < 0) deficit = 0;

    // Простая линейная смесь: вес busy + near_full*20 + penalty за дефицит
    return busy_ppm + near_full * 20 + deficit;
}

void set_socket_buffers(int fd) {
    char dt[DT_LOG_SIZE];
    int requested = set_socket_receive_buffer_kb * 1024;
    if (setsockopt(fd, SOL_SOCKET, SO_RCVBUF, &requested, sizeof(requested)) < 0)
        fprintf(stderr, "%s WARN [MAIN] Failed set SO_RCVBUF=%u for fd=%d\n", curr_dt(dt), requested, fd);
    requested = set_socket_send_buffer_kb * 1024;
    if (setsockopt(fd, SOL_SOCKET, SO_SNDBUF, &requested, sizeof(requested)) < 0)
        fprintf(stderr, "%s WARN [MAIN] Failed set SO_SNDBUF=%u for fd=%d\n", curr_dt(dt), requested, fd);
}


static int make_listen_socket(int port, const char *tag) {
    char dt[DT_LOG_SIZE];
    int fd = socket(AF_INET, SOCK_STREAM, 0);
    if (fd < 0) {
        perror("socket");
        exit(EXIT_FAILURE);
    }
    int optval = 1;
    if (setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &optval, sizeof(optval)) < 0) {
        perror("setsockopt(SO_REUSEADDR) failed");
        close(fd);
        exit(EXIT_FAILURE);
    }

    struct sockaddr_in addr;
    memset(&addr, 0, sizeof(addr));
    addr.sin_family = AF_INET;
    addr.sin_port = htons(port);
    addr.sin_addr.s_addr = INADDR_ANY;

    for (int i = 15; i >= 0; i--) {
        int rc = bind(fd, (struct sockaddr*)&addr, sizeof(addr));
        if (rc == 0) break;
        if (i == 0) {
            fprintf(stderr,"Exit. Try to change the port %d in settings or kill the process which using it\n", port);
            fprintf(stderr, "%s FATAL [MAIN] Error bind(%s:%d): %s\n", curr_dt(dt), tag, port, strerror(errno));
            exit(EXIT_FAILURE);
        }
        fprintf(stderr, "%s WARN [MAIN] %s port %d in use. Sleep 5 sec and retry x%d\n",
                curr_dt(dt), tag, port, i);
        sleep(5);
    }

    set_socket_buffers(fd);


    if (listen(fd, BACKLOG) < 0) {
        perror("listen");
        close(fd);
        exit(EXIT_FAILURE);
    }
    if (set_socket_blocking(fd, false) < 0) {
        close(fd);
        exit(EXIT_FAILURE);
    }

    fprintf(stderr, "%s INFO [MAIN] %s listen socket ready fd=%d port=%d\n",
            curr_dt(dt), tag, fd, port);
    return fd;
}


static int pick_pool_worker(int lo, int hi, target_half_t half) {
    worker_t *pool = (half == TARGET_LOWER_HALF) ? workers_lower : workers_upper;
    int n = (half == TARGET_LOWER_HALF)
              ? atomic_load(&worker_count_lower)
              : atomic_load(&worker_count_upper);
    worker_role_t role = (half == TARGET_LOWER_HALF) ? WR_CLIENT : WR_REPLICA;

    if (!pool) return -1;

    if (lo < 0) lo = 0;
    if (hi > n) hi = n;
    if (lo >= hi) return -1;

    if (half == TARGET_LOWER_HALF) {
        // num_clients is a high-water mark, not the number of live clients.
        // Rotate new client connections; compare only the first two candidates.
        static atomic_uint cursor = 0;
        unsigned span = (unsigned)(hi - lo);
        int pick = -1;
        unsigned offset = 0;
        unsigned seq = atomic_fetch_add_explicit(&cursor, 1, memory_order_relaxed);
        unsigned start = seq % span;

        for (unsigned step = 0; step < span; ++step) {
            int i = lo + (int)((start + step) % span);
            worker_t *w = &pool[i];
            if (w->role != role || w->epoll_fd <= 0 || !w->clients ||
                atomic_load(&w->is_quarantined) || w->self == 0)
                continue;

            bool room = atomic_load(&w->num_clients) < INITIAL_CLIENT_CAPACITY;
            if (!room) {
                // A full high-water mark may still contain holes. Do not read
                // slots without their lock or wait behind a worker's cleanup.
                if (pthread_mutex_trylock(&w->clients_lock) != 0) continue;
                if (w->clients && w->epoll_fd > 0 && !atomic_load(&w->is_quarantined)) {
                    for (int j = 0; j < INITIAL_CLIENT_CAPACITY; ++j) {
                        if (!w->clients[j]) { room = true; break; }
                    }
                }
                pthread_mutex_unlock(&w->clients_lock);
                if (!room) continue;
            }

            bool idle = !atomic_load_explicit(&w->active_tasks, memory_order_relaxed);
            if (pick < 0) {
                offset = step;
                pick = i;
                if (!idle) continue;
            } else if (idle) {
                offset = step;
                pick = i;
            }
            break;
        }
        if (pick >= 0) {
            // Continue after the chosen candidate, unless another selector has
            // already advanced the cursor. Registration rechecks under lock.
            unsigned expect = seq + 1;
            atomic_compare_exchange_strong_explicit(&cursor, &expect,
                seq + offset + 1, memory_order_relaxed, memory_order_relaxed);
        }
        return pick;
    }

    // Replica placement keeps its existing policy.
    int best = -1, min_nc = INT_MAX;

    for (int i = lo; i < hi; ++i) {
        worker_t *w = &pool[i];
        if (w->role != role) continue;
        if (w->epoll_fd <= 0 || !w->clients || atomic_load(&w->is_quarantined) || w->self == 0)
            continue;
        int nc = w->num_clients;
        if (nc < INITIAL_CLIENT_CAPACITY && nc < min_nc) {
            min_nc = nc; best = i;
        }
    }
    if (best >= 0) return best;

    // Фоллбек — просто первый готовый воркер
    for (int i = lo; i < hi; ++i) {
        worker_t *w = &pool[i];
        if (w->role != role) continue;
        if (w->epoll_fd > 0 && w->clients && !atomic_load(&w->is_quarantined))
            return i;
    }
    return -1;
}


//#define COOLDOWN_NS             50000000ULL   // 50 мс между расширениями
#define COOLDOWN_NS 1000000000ULL

#define ALPHA_1024              128            // α ≈ 0.125 для EWMA (в шкале /1024)
#define ONE_1024                1024

// пороги
#define TH_BUSY_MODERATE_PPM    850            // 85%
#define TH_NEARFULL_MODERATE_FR 50             // 50% воркеров почти полные
#define TH_NEARFULL_HARD_FR     80             // 80%
#define TH_SHRINK_BUSY_MAX_PPM 750
#define MIN_IDLE_WORKERS        1              // страховой резерв от блокировки всего пула

static inline unsigned long nsecs_now(void) {
    struct timespec ts; clock_gettime(CLOCK_MONOTONIC, &ts);
    return (unsigned long)ts.tv_sec * 1000000000ull + (unsigned long)ts.tv_nsec;
}

void expand_pool(target_half_t half, bool force, uint64_t cid) {
    if (atomic_load(&stop_resize_worker_pool)) return;
    char dt[DT_LOG_SIZE];

    _Atomic unsigned long *timers = (half == TARGET_LOWER_HALF)
                                  ? empty_since_ns_lower
                                  : empty_since_ns_upper;

    worker_t *pool = (half == TARGET_LOWER_HALF) ? workers_lower : workers_upper;
    pthread_t *ths = (half == TARGET_LOWER_HALF) ? worker_threads_lower : worker_threads_upper;
    _Atomic int *countp = (half == TARGET_LOWER_HALF) ? &worker_count_lower : &worker_count_upper;
    unsigned int cap = (half == TARGET_LOWER_HALF) ? max_workers_lower : max_workers_upper;
    pthread_mutex_t *lock = (half == TARGET_LOWER_HALF) ? &worker_mutex_lower : &worker_mutex_upper;
    worker_role_t role = (half == TARGET_LOWER_HALF) ? WR_CLIENT : WR_REPLICA;

    if (!pool || !ths || !cap) return;

    // --- fast path snapshot (no locks) ---
    int wc0 = atomic_load(countp);
    if (wc0 >= (int)cap) return;

    int from0 = 0;
    int to0 = wc0;

    int current0=0, busy0=0, near_full0=0, free_slots0=0;
    pool_aggregates_range_pools(half, from0, to0, &current0, &busy0, &near_full0, &free_slots0);

    int busy_ppm0 = (current0 > 0) ? (busy0 * 1000) / current0 : 0;

    // EWMA per-half
    int prev = atomic_load(&ewma_busy_permille_half[half]);
    int upd  = prev + ((ALPHA_1024 * (busy_ppm0 - prev)) / ONE_1024);
    atomic_store(&ewma_busy_permille_half[half], upd);

    // cooldown per-half
    unsigned long now0  = nsecs_now();
    unsigned long last0 = atomic_load(&last_expand_ns_half[half]);
    if (!force && now0 - last0 < COOLDOWN_NS) return;

    // Быстрая классификация без lock. Обычная занятость worker сама по
    // себе не означает нехватку емкости: для защиты от блокировки всего
    // пула достаточно поддерживать небольшой фиксированный idle-резерв.
    bool capacity_moderate0 = false;
    bool capacity_hard0 = false;
    int idle_workers0 = current0 - busy0;
    if (idle_workers0 < 0) idle_workers0 = 0;
    bool idle_guard0 = current0 > 0 && idle_workers0 < MIN_IDLE_WORKERS;

    if (current0 > 0 &&
        near_full0 * 100 >= current0 * TH_NEARFULL_HARD_FR)
        capacity_hard0 = true;
    if (free_slots0 <= current0) capacity_hard0 = true;

    if (current0 > 0 &&
        near_full0 * 100 >= current0 * TH_NEARFULL_MODERATE_FR)
        capacity_moderate0 = true;

    int reserve0 = (current0 * INITIAL_CLIENT_CAPACITY) / 50; // >=2% pool
    if (reserve0 < 32) reserve0 = 32;
    if (free_slots0 <= reserve0) capacity_moderate0 = true;

    if (!force && !idle_guard0 && !capacity_moderate0 && !capacity_hard0)
        return;

    // --- critical section: re-check and expand ---
    pthread_mutex_lock(lock);

    const int before = atomic_load(countp);
    if (before >= (int)cap) {
        pthread_mutex_unlock(lock);
        return;
    }

    // Несколько acceptor/monitor потоков могут одновременно пройти fast-path
    // со старым last_expand. Повторная проверка под mutex не дает им расширить
    // пул вслед за уже завершившимся расширением.
    unsigned long now = nsecs_now();
    unsigned long last = atomic_load(&last_expand_ns_half[half]);
    if (!force && now - last < COOLDOWN_NS) {
        pthread_mutex_unlock(lock);
        return;
    }

    int from = 0;
    int to = before;

    int current=0, busy=0, near_full=0, free_slots=0;
    pool_aggregates_range_pools(half, from, to, &current, &busy, &near_full, &free_slots);
    if (current < 0) current = 0;
    int busy_ppm = (current > 0) ? (busy * 1000) / current : 0;

    // Полностью пересчитываем решение после получения mutex. Fast-path мог
    // устареть, пока другой поток расширял пул.
    int idle_workers = current - busy;
    if (idle_workers < 0) idle_workers = 0;
    bool idle_guard = current > 0 && idle_workers < MIN_IDLE_WORKERS;

    bool capacity_moderate = false;
    bool capacity_hard = false;
    if (current > 0 &&
        near_full * 100 >= current * TH_NEARFULL_HARD_FR)
        capacity_hard = true;
    if (free_slots <= current) capacity_hard = true;

    if (current > 0 &&
        near_full * 100 >= current * TH_NEARFULL_MODERATE_FR)
        capacity_moderate = true;

    int reserve = (current * INITIAL_CLIENT_CAPACITY) / 50;
    if (reserve < 32) reserve = 32;
    if (free_slots <= reserve) capacity_moderate = true;

    if (!force && !idle_guard && !capacity_moderate && !capacity_hard) {
        pthread_mutex_unlock(lock);
        return;
    }

    // Страховой idle-резерв всегда растет по одному worker. Batch нужен
    // только при реальном исчерпании емкости по соединениям.
    int step = 1;
    if (capacity_hard) {
        step = before / 4; // up to +25% of this physical pool
        if (step < 2) step = 2;
        if (step > 8) step = 8;
    }
    if (before + step > (int)cap) step = (int)cap - before;
    if (step <= 0) {
        pthread_mutex_unlock(lock);
        return;
    }

    // Track created indices for forensic logs (bounded by step<=8)
    int holes = 0;
    int tail = 0;
    int made = 0;
    int ids[8];

    // Detect suspicious state: slots beyond worker_count have live epoll fd.
    int hidden = 0;
    for (int j = before; j < before + 8 && j < (int)cap; ++j) {
        if (pool[j].epoll_fd > 0) {
            hidden = 1;
            break;
        }
    }

    // create "batch"
    for (int k = 0; k < step; ++k) {
        int wc_now = atomic_load(countp);
        int new_i  = find_free_worker_slot_pools(half);

        if (new_i >= (int)cap) break;

        if (new_i < wc_now) holes++;

        if (timers)
            atomic_store(&timers[new_i], 0ul);

        init_worker(&pool[new_i], role, cid);

        int rc = pthread_create(&ths[new_i], NULL, worker_run, &pool[new_i]);
        if (rc != 0) {
            // Keep the slot clearly unusable if create failed
            fprintf(stderr, "pthread_create (worker expand): %s\n", strerror(rc));
            if (pool[new_i].epoll_fd > 0) close(pool[new_i].epoll_fd);
            pool[new_i].epoll_fd = 0;
            ths[new_i] = (pthread_t)0;
            break;
        }

        ids[made++] = new_i;

        // Update worker_count only when appended to tail
        if (new_i == wc_now) {
            int oldv = atomic_exchange(countp, wc_now + 1);
            fprintf(stderr, "%s WARN [WORKER=%015lu] worker_count_%s SET %d->%d\n",
                curr_dt(dt), cid,
                (half == TARGET_UPPER_HALF) ? "upper" : "lower",
                oldv, wc_now + 1);
            tail++;
        }
    }

    const int after = atomic_load(countp);

    if (made) {
        atomic_store(&last_expand_ns_half[half], nsecs_now());
    }

    {
        int off = 0;
        char idxbuf[256];
        off += snprintf(idxbuf + off, sizeof(idxbuf) - off, "[");
        for (int i = 0; i < made; ++i) {
            off += snprintf(idxbuf + off, sizeof(idxbuf) - off, "%s%d",
                            (i ? "," : ""), ids[i]);
            if (off >= (int)sizeof(idxbuf)) break;
        }
        snprintf(idxbuf + off, sizeof(idxbuf) - off, "]");

        fprintf(stderr,
            "%s INFO [POOL=%015lu] expand half=%d force=%d wc %d->%d step=%d created=%d tail=%d holes=%d "
            "range=[%d,%d) cur=%d busy=%d(%dppm) idle=%d idle_guard=%d capacity_moderate=%d capacity_hard=%d nf=%d free=%d ewma=%d hidden_tail=%d\n",
            curr_dt(dt), cid,
            (int)half, (int)force,
            before, after,
            step, made, tail, holes,
            from, to,
            current, busy, busy_ppm, idle_workers, (int)idle_guard,
            (int)capacity_moderate, (int)capacity_hard,
            near_full, free_slots,
            atomic_load(&ewma_busy_permille_half[half]),
            hidden);

        if (made) {
            fprintf(stderr,
                "%s INFO [POOL=%015lu] expand created_idx=%s\n",
                curr_dt(dt), cid, idxbuf);
        }
        if (hidden) {
            fprintf(stderr,
                "%s WARN [POOL=%015lu] expand sees hidden tail: wc_before=%d but some slots >=wc have epfd>0 (check who decremented worker_count_%s)\n",
                curr_dt(dt), cid, before,
                (half == TARGET_UPPER_HALF) ? "upper" : "lower");
        }
    }

    pthread_mutex_unlock(lock);
}

void try_expand_pool_pools(bool force, uint64_t cid) {
    int score_lower = pressure_score_half_pools(TARGET_LOWER_HALF);
    int score_upper = pressure_score_half_pools(TARGET_UPPER_HALF);
    target_half_t pick = (score_upper > score_lower) ? TARGET_UPPER_HALF : TARGET_LOWER_HALF;
    expand_pool(pick, force, cid);
}

static inline void delete_client_from_worker(worker_t *w, connection_t *c) {
    char dt[DT_LOG_SIZE];

    // Для лога берём cid только если t_handler ещё существует.
    // По твоей просьбе: не выводим "cid=..." текстом, оставляем только число в формате %015lu.
    const uint64_t cli_cid = (w && c && c->t_handler) ? c->t_handler->cid : 0;
    const int fd = (c ? transport_fd(&c->transport) : -1);

    if (!w || !c) {
        fprintf(stderr, "%s WARN [DELETE=%015lu] Client skip: w=%p c=%p fd=%d\n",
                curr_dt(dt), cli_cid, (void*)w, (void*)c, fd);
        return;
    }

    // Снимки для диагностики гонок (до лока): useful, если поля меняются параллельно
    const int owner_wi0  = c->owner_wi;
    const int owner_idx0 = c->owner_idx;

    pthread_mutex_lock(&w->clients_lock);

    int idx = -1;
    connection_t *before = NULL;

    // ВАЖНО: нельзя полагаться на c->owner_idx (он может уже указывать на новый воркер).
    // Ищем conn по указателю в таблице клиентов старого воркера.
    const int nc = w->num_clients;
    for (int i = 0; i < nc; ++i) {
        if (w->clients[i] == c) {
            idx = i;
            before = w->clients[i];
            break;
        }
    }

    if (idx >= 0) {
        fprintf(stderr,
                "%s DEBUG [DELETE=%015lu] Client w=%p(epoll=%d role=%s) slot=%d: %p -> NULL | "
                "conn=%p fd=%d owner_now(%d,%d) owner_before(%d,%d) nc=%d\n",
                curr_dt(dt),
                cli_cid,
                (void*)w, w->epoll_fd, safe_role_str(w->role),
                idx, (void*)before,
                (void*)c, fd,
                c->owner_wi, c->owner_idx,
                owner_wi0, owner_idx0,
                nc);

        w->clients[idx] = NULL;

        // Сжимаем хвост
        while (w->num_clients > 0 && w->clients[w->num_clients - 1] == NULL)
            w->num_clients--;

    } else {
        // Полезно видеть странные удаления, когда conn уже не числится за этим воркером
        fprintf(stderr,
                "%s WARN [DELETE=%015lu] Client not-found: w=%p(epoll=%d role=%s) nc=%d "
                "conn=%p fd=%d owner_now(%d,%d) owner_before(%d,%d)\n",
                curr_dt(dt),
                cli_cid,
                (void*)w, w->epoll_fd, safe_role_str(w->role),
                nc,
                (void*)c, fd,
                c->owner_wi, c->owner_idx,
                owner_wi0, owner_idx0);
    }

    pthread_mutex_unlock(&w->clients_lock);

    // ВАЖНО:
    // Здесь НЕ трогаем c->owner_wi / c->owner_idx:
    // после migrate_connection_to_new_worker эти поля уже принадлежат новому воркеру.
}


int migrate_connection_to_new_worker_pools(connection_t *conn, worker_t *dst, uint64_t cid) {
    char dt[DT_LOG_SIZE];

    if (!conn || !dst) {
        fprintf(stderr, "%s ERROR [RESCUE=%015lu] Migrate_connection_to_new_worker: conn=%p, dst=%p\n",
                curr_dt(dt), cid, (void*)conn, (void*)dst);
        return -1;
    }

    uint64_t cli_cid = conn->t_handler ? conn->t_handler->cid : 0;
    int fd = transport_fd(&conn->transport);

    // Вычисляем индекс dst внутри своего физического пула workers_lower/workers_upper
    int dst_idx = -1;
    worker_role_t dst_role = dst->role;
    worker_t *dst_pool = (dst_role == WR_REPLICA) ? workers_upper : workers_lower;
    int dst_limit = (dst_role == WR_REPLICA)
                  ? atomic_load(&worker_count_upper)
                  : atomic_load(&worker_count_lower);

    if (dst_pool) {
        for (int j = 0; j < dst_limit; ++j) {
            if (&dst_pool[j] == dst) {
                dst_idx = j;
                break;
            }
        }

        if (dst_idx < 0) {
            fprintf(stderr,
                    "%s ERROR [RESCUE=%015lu] Migrate_connection_to_new_worker: "
                    "cli_cid=%015lu, dst=%p not in %s pool (dst_idx=%d)\n",
                    curr_dt(dt), cid, cli_cid, (void*)dst,
                    (dst_role == WR_REPLICA) ? "UPPER" : "LOWER", dst_idx);
            return -1;
        }
    } else {
        fprintf(stderr,
                "%s ERROR [RESCUE=%015lu] Migrate_connection_to_new_worker: cli_cid=%015lu, %s pool=NULL\n",
                curr_dt(dt), cid, cli_cid,
                (dst_role == WR_REPLICA) ? "UPPER" : "LOWER");
        return -1;
    }

    // Быстрые проверки готовности dst
    if (dst->epoll_fd <= 0 || dst->clients == NULL || atomic_load(&dst->is_quarantined)) {
        fprintf(stderr,
                "%s WARN [RESCUE=%015lu] Dst worker not ready: cli_cid=%015lu, dst=%p idx=%d epoll=%d clients=%p quarantined=%d\n",
                curr_dt(dt), cid, cli_cid, (void*)dst, dst_idx,
                dst->epoll_fd, (void*)dst->clients,
                (int)atomic_load(&dst->is_quarantined));
        return -1;
    }

    // Переводим коннект в неблокирующий режим (идемпотентно)
    conn->mode = NONBLOCKING_MODE;

    pthread_mutex_lock(&dst->clients_lock);

    // Повторная проверка под локом — чтобы не схватить race с карантином/закрытием epoll
    if (dst->epoll_fd <= 0 || dst->clients == NULL || atomic_load(&dst->is_quarantined)) {
        fprintf(stderr,
                "%s WARN [RESCUE=%015lu] Dst locked-skip: cli_cid=%015lu, dst=%p idx=%d epoll=%d clients=%p quarantined=%d\n",
                curr_dt(dt), cid, cli_cid, (void*)dst, dst_idx,
                dst->epoll_fd, (void*)dst->clients,
                (int)atomic_load(&dst->is_quarantined));
        pthread_mutex_unlock(&dst->clients_lock);
        return -1;
    }

    // Ищем "дырку" или добавляем в хвост
    int pos = -1;
    int appended = 0;

    for (int i = 0; i < dst->num_clients; ++i) {
        if (dst->clients[i] == NULL) {
            pos = i;
            break;
        }
    }

    int old_num_clients = dst->num_clients;
    if (pos == -1) {
        if (dst->num_clients < INITIAL_CLIENT_CAPACITY) {
            pos = dst->num_clients++;
            appended = 1;
        } else {
            fprintf(stderr,
                    "%s WARN [RESCUE=%015lu] Dst full cli_cid=%015lu, fd=%d dst_idx=%d num_clients=%d cap=%d\n",
                    curr_dt(dt), cid, cli_cid, fd, dst_idx, dst->num_clients, INITIAL_CLIENT_CAPACITY);
            pthread_mutex_unlock(&dst->clients_lock);
            return -1;
        }
    }

    // Сохраняем старого owner’а для отката
    int prev_owner_wi = conn->owner_wi;
    int prev_owner_idx = conn->owner_idx;

    int curr_owner_wi = conn->owner_wi;
    int curr_owner_idx = conn->owner_idx;

    connection_t *prev_slot = dst->clients[pos];

    fprintf(stderr,
            "%s DEBUG [RESCUE=%015lu] Slot-assign BEGIN cli_cid=%015lu, fd=%d dst_idx=%d pos=%d appended=%d "
            "num_clients %d->%d slot_prev=%p owner(%d,%d)->(%d,%d)\n",
            curr_dt(dt), cid, cli_cid, fd, dst_idx, pos, appended,
            old_num_clients, dst->num_clients,
            (void*)prev_slot, prev_owner_wi, prev_owner_idx, dst_idx, pos);

    // Привязываем коннект к новому воркеру
    dst->clients[pos] = conn;
    conn->owner_wi = dst_idx;
    conn->owner_idx = pos;

    curr_owner_wi = conn->owner_wi;
    curr_owner_idx = conn->owner_idx;

    fprintf(stderr,
            "%s DEBUG [RESCUE=%015lu] Slot-assign DONE cli_cid=%015lu, fd=%d dst_idx=%d pos=%d slot_now=%p owner_now(%d,%d)\n",
            curr_dt(dt), cid, cli_cid, fd, dst_idx, pos,
            (void*)dst->clients[pos], curr_owner_wi, curr_owner_idx);

    pthread_mutex_unlock(&dst->clients_lock);

    // Сокет должен быть неблокирующим; вызов идемпотентен
    if (set_socket_blocking(transport_fd(&conn->transport), false) < 0) {
        perror("set_socket_blocking(false)");

        // Откат таблицы клиентов у dst + лог
        pthread_mutex_lock(&dst->clients_lock);
        connection_t *slot_now =
            (pos >= 0 && pos < dst->num_clients) ? dst->clients[pos] : NULL;

        fprintf(stderr,
                "%s ERROR [RESCUE=%015lu] Rollback(set_socket_blocking) cli_cid=%015lu, fd=%d dst_idx=%d pos=%d "
                "slot_now=%p appended=%d num_clients=%d\n",
                curr_dt(dt), cid, cli_cid, fd, dst_idx, pos,
                (void*)slot_now, appended, dst->num_clients);

        if (pos >= 0 && pos < dst->num_clients && dst->clients[pos] == conn) {
            dst->clients[pos] = NULL;
            if (appended) {
                while (dst->num_clients > 0 && dst->clients[dst->num_clients - 1] == NULL)
                    dst->num_clients--;
            }
        }
        pthread_mutex_unlock(&dst->clients_lock);

        fprintf(stderr,
                "%s ERROR [RESCUE=%015lu] Rollback done cli_cid=%015lu, fd=%d owner(%d,%d)->(%d,%d)\n",
                curr_dt(dt), cid, cli_cid, fd, curr_owner_wi, curr_owner_idx, prev_owner_wi, prev_owner_idx);

        // Возвращаем owner’а в исходное состояние
        conn->owner_wi = prev_owner_wi;
        conn->owner_idx = prev_owner_idx;

        curr_owner_wi = conn->owner_wi;
        curr_owner_idx = conn->owner_idx;

        return -1;
    }

    // Регистрация в epoll нового воркера
    struct epoll_event ev;
    ev.data.ptr = conn;
    ev.events = EPOLLIN | EPOLLRDHUP | EPOLLONESHOT;

    if (epoll_ctl(dst->epoll_fd, EPOLL_CTL_ADD, transport_fd(&conn->transport), &ev) < 0) {
        if (errno == EEXIST) {
            // На всякий случай: если уже был в этом epoll — пробуем MOD
            if (epoll_ctl(dst->epoll_fd, EPOLL_CTL_MOD, transport_fd(&conn->transport), &ev) == 0) {
                unsigned at = atomic_load(&dst->active_tasks);
                fprintf(stderr,
                        "%s INFO [RESCUE=%015lu] Client EEXIST->MOD, cli_cid=%015lu, fd=%d -> W[%d].epoll=%d "
                        "(num_clients=%d active=%u)\n",
                        curr_dt(dt), cid, cli_cid, fd,
                        dst_idx, dst->epoll_fd, dst->num_clients, at);
                return 0;
            }
        }

        perror("epoll_ctl (ADD)");

        // Откат таблицы клиентов у dst + лог
        pthread_mutex_lock(&dst->clients_lock);
        connection_t *slot_now =
            (pos >= 0 && pos < dst->num_clients) ? dst->clients[pos] : NULL;

        fprintf(stderr,
                "%s ERROR [RESCUE=%015lu] Rollback(epoll_add) cli_cid=%015lu, fd=%d dst_idx=%d epoll=%d pos=%d "
                "slot_now=%p appended=%d num_clients=%d errno=%d\n",
                curr_dt(dt), cid, cli_cid, fd, dst_idx, dst->epoll_fd, pos,
                (void*)slot_now, appended, dst->num_clients, errno);

        if (pos >= 0 && pos < dst->num_clients && dst->clients[pos] == conn) {
            dst->clients[pos] = NULL;
            if (appended) {
                while (dst->num_clients > 0 && dst->clients[dst->num_clients - 1] == NULL)
                    dst->num_clients--;
            }
        }
        pthread_mutex_unlock(&dst->clients_lock);

        fprintf(stderr,
                "%s ERROR [RESCUE=%015lu] Rollback done cli_cid=%015lu, fd=%d owner(%d,%d)->(%d,%d)\n",
                curr_dt(dt), cid, cli_cid, fd, curr_owner_wi, curr_owner_idx, prev_owner_wi, prev_owner_idx);

        // Возвращаем owner’а в исходное состояние
        conn->owner_wi = prev_owner_wi;
        conn->owner_idx = prev_owner_idx;

        curr_owner_wi = conn->owner_wi;
        curr_owner_idx = conn->owner_idx;

        return -1;
    }

    unsigned at = atomic_load(&dst->active_tasks);
    fprintf(stderr,
            "%s INFO [RESCUE=%015lu] Done cli_cid=%015lu, fd=%d -> W[%d].epoll=%d (num_clients=%d active=%u) owner=(%d,%d)\n",
            curr_dt(dt), cid, cli_cid, fd, dst_idx, dst->epoll_fd, dst->num_clients, at, curr_owner_wi, curr_owner_idx);
    return 0;
}

// Головная функция спасения клиентов "застрявшего" воркера.
// Вызывается монитором после установки карантина и (как минимум логического)
// "отключения" воркера, но ДО join старого worker_run.
// Регистрирует conn сразу в соответствующем физическом пуле.
void rescue_all_clients_pools(worker_t *stalled, int stalled_index) {
    if (!stalled) return;

    char dt[DT_LOG_SIZE];
    uint64_t cid = get_new_cid();

    // Role/half snapshot early (for consistent logs even if fields change later)
    const worker_role_t role = stalled->role;
    const target_half_t half = half_for_role(role);

    worker_t *dst_pool = (role == WR_REPLICA) ? workers_upper : workers_lower;

    const int epfd0 = stalled->epoll_fd;
    const int nc0   = stalled->num_clients;

    fprintf(stderr,
        "%s WARN [RESCUE=%015lu] Rescue begin stalled=W[%d] w=%p role=%s epfd=%d num_clients=%d quarantined=%d ready_migrate=%d ready_epoll=%d gen=%lu tid=%lu running=%d\n",
        curr_dt(dt), cid,
        stalled_index, (void*)stalled, safe_role_str(role),
        epfd0, nc0,
        (int)atomic_load(&stalled->is_quarantined),
        (int)atomic_load(&stalled->ready_to_migrate),
        (int)atomic_load(&stalled->ready_to_epoll),
        atomic_load(&stalled->gen),
        atomic_load(&stalled->os_tid),
        (int)atomic_load(&stalled->running));

    // --- 1) Snapshot candidates ---
    connection_t **snapshot = NULL;
    int snapshot_cnt = 0;

    pthread_mutex_lock(&stalled->clients_lock);

    const int nc = stalled->num_clients;
    if (nc > 0) {
        snapshot = (connection_t**)malloc((size_t)nc * sizeof(connection_t*));
        if (!snapshot) {
            pthread_mutex_unlock(&stalled->clients_lock);
            perror("malloc snapshot in rescue_all_clients");
            fprintf(stderr,
                "%s ERROR [RESCUE=%015lu] Malloc snapshot failed stalled=W[%d] nc=%d -> abort rescue\n",
                curr_dt(dt), cid, stalled_index, nc);
            return;
        }

        for (int i = 0; i < nc; ++i) {
            connection_t *conn = stalled->clients[i];
            if (!conn) continue;

            // Fast filters only; do NOT touch deep t_handler fields under this lock
            if (atomic_load(&conn->state) == STATE_FREED) continue;
            if (atomic_load(&conn->in_processing) > 0) continue;
            if (conn->owner_wi != stalled_index) continue;

            snapshot[snapshot_cnt++] = conn;
        }
    }

    pthread_mutex_unlock(&stalled->clients_lock);

    if (snapshot_cnt == 0) {
        fprintf(stderr,
            "%s INFO [RESCUE=%015lu] No candidates stalled=W[%d] nc=%d\n",
            curr_dt(dt), cid, stalled_index, nc);
        free(snapshot);
        return;
    }

    fprintf(stderr,
        "%s INFO [RESCUE=%015lu] Snapshot stalled=W[%d] candidates=%d/%d\n",
        curr_dt(dt), cid, stalled_index, snapshot_cnt, nc);

    int rescued = 0;
    int failed  = 0;
    int skipped = 0;
    int expand_forced = 0;

    // --- 2) Migrate candidates ---
    for (int k = 0; k < snapshot_cnt; ++k) {
        connection_t *conn = snapshot[k];
        if (!conn) { skipped++; continue; }

        // Capture cheap identifiers early (avoid deep deref of t_handler if it might already be poisoned)
        const int fd = transport_fd(&conn->transport);

        uint64_t cli_cid = 0;
        table_handler_t *th = conn->t_handler;
        if (th) cli_cid = th->cid;  // still a potential UAF in a broken system, but best available without redesign

        const int st = atomic_load(&conn->state);
        const int owner_wi = conn->owner_wi;
        const unsigned in_proc = atomic_load(&conn->in_processing);

        if (st == STATE_FREED || owner_wi != stalled_index || in_proc > 0) {
            fprintf(stderr,
                "%s INFO [RESCUE=%015lu] Skip cli_cid=%015lu fd=%d state=%d owner_wi=%d in_processing=%u\n",
                curr_dt(dt), cid, cli_cid, fd, st, owner_wi, in_proc);
            skipped++;
            continue;
        }

        // Escalation: too many migrations -> force expand once per rescue pass
        if (atomic_load(&conn->migrate_count) > 2) {
            if (!expand_forced) {
                expand_pool(half, true, cid);
                expand_forced = 1;
            }
            atomic_store(&conn->migrate_count, 0);
        }

        int dst_idx = pick_worker_index_by_role_pools(role);
        if (dst_idx < 0) {
            if (!expand_forced) {
                expand_pool(half, true, cid);
                expand_forced = 1;
            }
            dst_idx = pick_worker_index_by_role_pools(role);
        }

        // Remove from stalled BEFORE attempting to place elsewhere,
        // so we don't touch stalled internals for this conn after that point.
        delete_client_from_worker(stalled, conn);

        if (dst_idx < 0 || !dst_pool) {
            fprintf(stderr,
                "%s WARN [RESCUE=%015lu] No dst for role=%s cli_cid=%015lu fd=%d (stalled=W[%d]) -> close\n",
                curr_dt(dt), cid, safe_role_str(role), cli_cid, fd, stalled_index);
            close_conn(conn);
            free(conn);
            failed++;
            continue;
        }

        worker_t *dst = &dst_pool[dst_idx];
        if (dst == stalled) {
            fprintf(stderr,
                "%s WARN [RESCUE=%015lu] Found dst=stalled dst_idx=%d cli_cid=%015lu fd=%d -> close\n",
                curr_dt(dt), cid, dst_idx, cli_cid, fd);
            close_conn(conn);
            free(conn);
            failed++;
            continue;
        }

        // Best-effort cleanup of old epoll (if still open); ignore errors.
        int epfd_stalled = stalled->epoll_fd;
        if (epfd_stalled > 0 && fd >= 0) {
            (void)epoll_ctl(epfd_stalled, EPOLL_CTL_DEL, fd, NULL);
        }

        fprintf(stderr,
            "%s INFO [RESCUE=%015lu] Try migrate_attempt cli_cid=%015lu fd=%d from=W[%d](epfd=%d gen=%lu) to=W[%d](epfd=%d gen=%lu)\n",
            curr_dt(dt), cid, cli_cid, fd,
            stalled_index, epfd_stalled, atomic_load(&stalled->gen),
            dst_idx, dst->epoll_fd, atomic_load(&dst->gen));

        atomic_fetch_add(&conn->migrate_count, 1);

        const int mrc = migrate_connection_to_new_worker_pools(conn, dst, cid);
        if (mrc != 0) {
            fprintf(stderr,
                "%s ERROR [RESCUE=%015lu] Migrate failed cli_cid=%015lu fd=%d from=W[%d] to=W[%d] rc=%d -> close\n",
                curr_dt(dt), cid, cli_cid, fd, stalled_index, dst_idx, mrc);
            close_conn(conn);
            free(conn);
            failed++;
            continue;
        }

        fprintf(stderr,
            "%s INFO [RESCUE=%015lu] Done migrated cli_cid=%015lu fd=%d from=W[%d] to=W[%d]\n",
            curr_dt(dt), cid, cli_cid, fd, stalled_index, dst_idx);
        rescued++;
    }

    fprintf(stderr,
        "%s WARN [RESCUE=%015lu] Done stalled=W[%d] rescued=%d failed=%d skipped=%d snapshot_cnt=%d expand_forced=%d\n",
        curr_dt(dt), cid, stalled_index, rescued, failed, skipped, snapshot_cnt, expand_forced);

    free(snapshot);
}

int register_conn_pools(connection_t *c, target_half_t half) {
    char dt[DT_LOG_SIZE];
    if (!c) return -1;

    const uint64_t cid = c->t_handler ? c->t_handler->cid : 0;
    const int fd = transport_fd(&c->transport);
    const int owner_wi = c->owner_wi;
    const int owner_idx = c->owner_idx;

    c->mode = NONBLOCKING_MODE;

    // Пытаемся заранее подрасти именно нужный пул
    expand_pool(half, false, cid);

    const int max_tries = 10;
    for (int try_no = 0; try_no <= max_tries; ++try_no) {
        worker_t *pool = (half == TARGET_LOWER_HALF) ? workers_lower : workers_upper;
        int limit = (half == TARGET_LOWER_HALF)
                  ? atomic_load(&worker_count_lower)
                  : atomic_load(&worker_count_upper);

        int from = 0;
        int to = limit;

        fprintf(stderr, "%s INFO [REGISTER=%015lu] Try attempt=%d/%d fd=%d half=%s range=[%d,%d) wc=%d sp=%d\n",
                curr_dt(dt), cid, try_no, max_tries, fd,
                (half==TARGET_UPPER_HALF) ? "UPPER" : "LOWER",
                from, to, limit, 0);

        int wi = -1;
        if (try_no == max_tries) {
            expand_pool(half, true, cid);

            pool = (half == TARGET_LOWER_HALF) ? workers_lower : workers_upper;
            limit = (half == TARGET_LOWER_HALF)
                  ? atomic_load(&worker_count_lower)
                  : atomic_load(&worker_count_upper);

            wi = pick_pool_worker(0, limit, half);
            fprintf(stderr, "%s INFO [REGISTER=%015lu] Result final-pick fd=%d res_wi=%d wc=%d\n",
                    curr_dt(dt), cid, fd, wi, limit);
            if (wi < 0) { expand_pool(half, true, cid); continue; }
        } else {
            usleep(try_no * 1000);
            if (from >= to) { expand_pool(half, false, cid); continue; }
            wi = pick_pool_worker(from, to, half);
            if (wi < 0) { expand_pool(half, false, cid); continue; }
        }

        if (!pool || wi < 0 || wi >= limit) {
            fprintf(stderr, "%s WARN [REGISTER=%015lu] Pool/index invalid fd=%d half=%s wi=%d limit=%d pool=%p\n",
                    curr_dt(dt), cid, fd,
                    (half==TARGET_UPPER_HALF) ? "UPPER" : "LOWER",
                    wi, limit, (void*)pool);
            expand_pool(half, false, cid);
            continue;
        }

        worker_t *w = &pool[wi];

        // Быстрая проверка до лока
        if (w->epoll_fd <= 0 || !w->clients || atomic_load(&w->is_quarantined)) {
            fprintf(stderr, "%s WARN [REGISTER=%015lu] Check prelock-skip fd=%d wi=%d epoll=%d clients=%p quarantined=%d\n",
                    curr_dt(dt), cid, fd, wi, w->epoll_fd, (void*)w->clients, (int)atomic_load(&w->is_quarantined));
            expand_pool(half, false, cid);
            continue;
        }

        pthread_mutex_lock(&w->clients_lock);

        // Значимая проверка под локом
        if (w->epoll_fd <= 0 || !w->clients || atomic_load(&w->is_quarantined)) {
            fprintf(stderr, "%s WARN [REGISTER=%015lu] Check locked-skip fd=%d wi=%d epoll=%d clients=%p quarantined=%d\n",
                    curr_dt(dt), cid, fd, wi, w->epoll_fd, (void*)w->clients, (int)atomic_load(&w->is_quarantined));
            pthread_mutex_unlock(&w->clients_lock);
            expand_pool(half, false, cid);
            continue;
        }

        // Поиск дырки либо добавление в хвост
        int pos = -1;
        int added = 0;

        for (int i = 0; i < w->num_clients; ++i) {
            if (w->clients[i] == NULL) { pos = i; break; }
        }

        int old_nc = w->num_clients;
        if (pos == -1) {
            if (w->num_clients < INITIAL_CLIENT_CAPACITY) {
                pos = w->num_clients++;
                added = 1;
            } else {
                fprintf(stderr, "%s WARN [REGISTER=%015lu] Reached full fd=%d wi=%d num_clients=%d cap=%d\n",
                        curr_dt(dt), cid, fd, wi, w->num_clients, INITIAL_CLIENT_CAPACITY);
                pthread_mutex_unlock(&w->clients_lock);
                expand_pool(half, false, cid);
                continue;
            }
        }

        // Логируем изменения слота и owner'ов
        connection_t *prev_slot = w->clients[pos];
        int prev_owner_wi = c->owner_wi;
        int prev_owner_idx = c->owner_idx;

        fprintf(stderr,
                "%s DEBUG [REGISTER=%015lu] Slot-assign BEGIN fd=%d wi=%d pos=%d appended=%d "
                "num_clients %d->%d slot_prev=%p conn=%p owner(%d,%d)->(%d,%d)\n",
                curr_dt(dt), cid, fd, wi, pos, added,
                old_nc, w->num_clients,
                (void*)prev_slot, (void*)c,
                prev_owner_wi, prev_owner_idx, wi, pos);

        w->clients[pos] = c;
        c->owner_wi = wi;
        c->owner_idx = pos;

        fprintf(stderr,
                "%s DEBUG [REGISTER=%015lu] Slot-assign DONE fd=%d wi=%d pos=%d slot_now=%p conn=%p owner_now(%d,%d)\n",
                curr_dt(dt), cid, fd, wi, pos,
                (void*)w->clients[pos], (void*)c,
                c->owner_wi, c->owner_idx);

        // Registration-time snapshots for logs after ownership passes to the worker.
        const int epfd = w->epoll_fd;
        const int nc = w->num_clients;
        const unsigned active = atomic_load(&w->active_tasks);
        pthread_mutex_unlock(&w->clients_lock);

        // Сокет должен быть неблокирующим; вызов идемпотентен
        if (set_socket_blocking(transport_fd(&c->transport), false) < 0) {
            perror("set_socket_blocking(false)");

            // Откат таблицы клиентов + лог
            pthread_mutex_lock(&w->clients_lock);
            connection_t *slot_now = (pos >= 0 && pos < w->num_clients) ? w->clients[pos] : NULL;

            fprintf(stderr,
                    "%s ERROR [REGISTER=%015lu] Rollback(set_socket_blocking) fd=%d wi=%d pos=%d "
                    "slot_now=%p expected=%p appended=%d num_clients=%d\n",
                    curr_dt(dt), cid, fd, wi, pos,
                    (void*)slot_now, (void*)c,
                    added, w->num_clients);

            if (pos >= 0 && pos < w->num_clients && w->clients[pos] == c) {
                w->clients[pos] = NULL;
                if (added) {
                    while (w->num_clients > 0 && w->clients[w->num_clients - 1] == NULL)
                        w->num_clients--;
                }
            }
            pthread_mutex_unlock(&w->clients_lock);

            fprintf(stderr,
                    "%s ERROR [REGISTER=%015lu] Rollback done fd=%d conn=%p owner(%d,%d)->(-1,-1)\n",
                    curr_dt(dt), cid, fd, (void*)c, c->owner_wi, c->owner_idx);

            c->owner_wi = -1;
            c->owner_idx = -1;
            return -1;
        }

        // Регистрация в epoll
        struct epoll_event ev;
        ev.data.ptr = c;
        ev.events = EPOLLIN | EPOLLRDHUP | EPOLLONESHOT;

        // After successful ADD/MOD, the worker may immediately free conn,
        // even before epoll_ctl returns. Use only saved values and return success.
        if (epoll_ctl(w->epoll_fd, EPOLL_CTL_ADD, transport_fd(&c->transport), &ev) < 0) {
            if (errno == EEXIST) {
                if (epoll_ctl(w->epoll_fd, EPOLL_CTL_MOD, transport_fd(&c->transport), &ev) == 0) {
                    fprintf(stderr, "%s INFO [REGISTER=%015lu] Success EEXIST->MOD fd=%d -> %s W[%d].epoll=%d (num_clients=%d active=%u)\n",
                            curr_dt(dt), cid, fd,
                            (half==TARGET_UPPER_HALF) ? "UPPER" : "LOWER",
                            wi, epfd, nc, active);
                    return 0;
                }
            }

            perror("epoll_ctl (ADD)");

            // Откат таблицы клиентов + лог
            pthread_mutex_lock(&w->clients_lock);
            connection_t *slot_now = (pos >= 0 && pos < w->num_clients) ? w->clients[pos] : NULL;

            fprintf(stderr,
                    "%s ERROR [REGISTER=%015lu] Rollback(epoll_add) fd=%d wi=%d epoll=%d pos=%d "
                    "slot_now=%p expected=%p appended=%d num_clients=%d errno=%d\n",
                    curr_dt(dt), cid, fd, wi, w->epoll_fd, pos,
                    (void*)slot_now, (void*)c,
                    added, w->num_clients, errno);

            if (pos >= 0 && pos < w->num_clients && w->clients[pos] == c) {
                w->clients[pos] = NULL;
                if (added) {
                    while (w->num_clients > 0 && w->clients[w->num_clients - 1] == NULL)
                        w->num_clients--;
                }
            }
            pthread_mutex_unlock(&w->clients_lock);

            fprintf(stderr,
                    "%s ERROR [REGISTER=%015lu] Rollback done fd=%d conn=%p owner(%d,%d)->(-1,-1)\n",
                    curr_dt(dt), cid, fd, (void*)c, c->owner_wi, c->owner_idx);

            c->owner_wi = -1;
            c->owner_idx = -1;

            expand_pool(half, false, cid);
            continue;
        }

        fprintf(stderr, "%s INFO [REGISTER=%015lu] OK fd=%d -> %s W[%d].epoll=%d (num_clients=%d active=%u) owner=(%d,%d)\n",
                curr_dt(dt), cid, fd,
                (half==TARGET_UPPER_HALF) ? "UPPER" : "LOWER",
                wi, epfd, nc, active,
                wi, pos);

        return 0;
    }

    fprintf(stderr, "%s WARN [REGISTER=%015lu] FAIL no capacity in %s half for fd=%d\n",
            curr_dt(dt), cid,
            (half==TARGET_UPPER_HALF) ? "UPPER" : "LOWER", fd);

    return -1;
}


// ---------- Поток-акцептор ----------------------------------------
void* acceptor_thread_pools(void *arg) {
    char dt[DT_LOG_SIZE];

    acceptor_args_t *a = (acceptor_args_t*)arg;
    const int server_fd = a->listen_fd;
    const int port = a->port;
    const target_half_t half = a->half;
    uint64_t cid = get_new_cid();

    fprintf(stderr, "%s INFO [ACCEPTOR=%015lu] Started on port %d, target=%s half\n",
            curr_dt(dt), cid, port, (half==TARGET_UPPER_HALF) ? "UPPER" : "LOWER");
    free(a);

    for (;;) {
        struct sockaddr_in client_addr;
        socklen_t client_len = sizeof(client_addr);

        int client_fd = accept(server_fd, (struct sockaddr *)&client_addr, &client_len);
        if (client_fd < 0) {
            if (errno == EAGAIN || errno == EWOULDBLOCK || errno == EINTR) {
                // неблокирующий listen или прерывание — чуть подождём
                usleep(1000);
                continue;
            }
            perror("accept");
            continue;
        }

        set_socket_buffers(client_fd);

        if (stop_new_client_requests) {
            close(client_fd);
            usleep(10000);
            continue;
        }

        if (blocking_socket_mode == false)
            (void)set_socket_blocking(client_fd, false);

        if (set_tcp_nodelay) {
            int nd = 1;
            if (setsockopt(client_fd, IPPROTO_TCP, TCP_NODELAY, &nd, sizeof(nd)) == -1) {
                perror("client fd setsockopt TCP_NODELAY");
            }
        }

        int fdfl = fcntl(client_fd, F_GETFD);
        if (fdfl >= 0) (void)fcntl(client_fd, F_SETFD, fdfl | FD_CLOEXEC);

        if (stop_any_client_requests) {
            fprintf(stderr, "%s ERROR [ACCEPTOR=%015lu] Refused client fd=%d (low memory)\n",
                curr_dt(dt), cid, client_fd);
            close(client_fd);
            // не блокируем акцептор на 10 сек, чтобы не залипать при шквале
            usleep(5000);
            continue;
        }

        char ip[64]; inet_ntop(AF_INET, &client_addr.sin_addr, ip, sizeof(ip));
        int rport = ntohs(client_addr.sin_port);

        connection_t *conn = calloc(1, sizeof(connection_t));
        if (!conn) { perror("calloc connection_t"); close(client_fd); continue; }

        conn->has_table = false;
        transport_init(&conn->transport, client_fd);
        if (!transport_prepare_server(&conn->transport)) {
            fprintf(stderr, "%s ERROR [ACCEPTOR=%015lu] TLS transport setup failed, fd=%d\n",
                    curr_dt(dt), cid, client_fd);
            transport_close(&conn->transport);
            free(conn);
            continue;
        }

        pthread_arg_t *parg = malloc(sizeof(pthread_arg_t));
        if (!parg) {
            perror("malloc pthread_arg_t");
            transport_close(&conn->transport);
            free(conn);
            continue;
        }

        parg->client_address = client_addr;
        snprintf(parg->ip, sizeof(parg->ip), "%s", ip);
        snprintf(parg->port, sizeof(parg->port), "%d", rport);
        parg->transport = &conn->transport;

        conn->t_handler = init_connection((void *)parg);
        if (!conn->t_handler) {
            fprintf(stderr, "%s ERROR [ACCEPTOR=%015lu] Init connection failed, fd=%d\n",
                curr_dt(dt), cid, client_fd);
            transport_close(&conn->transport);
            free(conn); free(parg);
            continue;
        }

        conn->t_handler->conn_father = (struct connection_t*)conn;
        atomic_store(&conn->state, STATE_AUTH_PENDING);
        if (blocking_socket_mode == true) {
            conn->mode = BLOCKING_MODE;
            set_socket_blocking(client_fd, true);
            fprintf(stderr, "%s INFO [ACCEPTOR=%015lu] Accepted connection from %s:%s (fd=%d) -> client thread started\n",
                   curr_dt(dt), cid, parg->ip, parg->port, client_fd);

            // Создаём отдельный поток для обслуживания данного клиента
            pthread_t client_thread;
            if (pthread_create(&client_thread, NULL, client_handler_thread, conn) != 0) {
                perror("pthread_create (client_handler_thread)");
                close_conn(conn);
                free(conn);
                conn = NULL;
                free(parg);
                continue;
            }
            pthread_detach(client_thread);
        } else {
            conn->mode = NONBLOCKING_MODE;
            atomic_store(&conn->migrate_count, 0);
            fprintf(stderr, "%s INFO [ACCEPTOR=%015lu] Accepted %s:%d (fd=%d) -> %s half registration\n",
                    curr_dt(dt), cid, ip, rport, client_fd,
                    (half==TARGET_UPPER_HALF) ? "UPPER" : "LOWER");

            // Легкий prescale только целевой половины. Общий пул фоново
            // контролируется monitor_pools().
            expand_pool(half, false, cid);

            // регистрация в половине с одной повторной попыткой после расширения
            if (register_conn_pools(conn, half) != 0) {
                expand_pool(half, false, cid);
                if (register_conn_pools(conn, half) != 0) {
                    fprintf(stderr, "%s WARN [ACCEPTOR=%015lu] No capacity in %s half for fd=%d -> closing\n",
                            curr_dt(dt), cid, (half==TARGET_UPPER_HALF) ? "UPPER" : "LOWER", client_fd);
                    close_conn(conn); // корректно освобождает всё, т.к. init_connection уже был
                    free(conn);
                    conn = NULL;
                    free(parg);
                    continue;
                }
            }
        }

        // init_connection потребовал parg — дальше не нужен
        free(parg);
    }

    // not reached
    return NULL;
}


void close_all_clients_for_worker_pools(worker_t *stalled, int stalled_index, uint64_t cid) {
    char dt[DT_LOG_SIZE];
    fprintf(stderr, "%s WARN [MONITOR=%015lu] Closing %d clients from stalled W[%d] epoll_fd=%d (role=%d)\n",
            curr_dt(dt), cid, stalled->num_clients, stalled_index, stalled->epoll_fd, (int)stalled->role);

    pthread_mutex_lock(&stalled->clients_lock);

    for (int i = 0; i < stalled->num_clients; ++i) {
        connection_t *conn = stalled->clients[i];
        stalled->clients[i] = NULL;

        if (!conn) continue;

        // Если conn уже помечен как freed — всё равно полезно проверить owner
        if (conn->owner_wi != stalled_index) {
            log_owner_mismatch("MIGRATE_ALL", stalled_index, i, stalled, conn);
#ifndef NDEBUG
            assert(conn->owner_wi == stalled_index);
#endif
        }

        // The worker has been joined. Even STATE_FREED connections still
        // have an owner here; close_conn is harmless after handler cleanup.
        if (stalled->epoll_fd > 0 && transport_fd(&conn->transport) >= 0) {
            epoll_ctl(stalled->epoll_fd, EPOLL_CTL_DEL, transport_fd(&conn->transport), NULL);
        }

        // ВАЖНО: close_conn/free только после проверки owner
        close_conn(conn);
        free(conn);
        conn = NULL;
    }

    stalled->num_clients = 0;

    pthread_mutex_unlock(&stalled->clients_lock);

    fprintf(stderr, "%s INFO [MONITOR=%015lu] All clients from stalled W[%d] were closed\n",
            curr_dt(dt), cid, stalled_index);
}

typedef struct monitor_quarantine_task_s {
    int index;
    worker_t *worker;
    pthread_t th_before;
    pthread_t self_before;
    unsigned long gen_before;
    unsigned long tid_before;
    bool running_before;
    int epfd_before;
} monitor_quarantine_task_t;

static void* monitor_quarantine_worker_pools(void *arg) {
    monitor_quarantine_task_t *t = (monitor_quarantine_task_t*)arg;
    int i = t->index;
    worker_t *w = t->worker;
    pthread_t th_before = t->th_before;
    pthread_t self_before = t->self_before;
    unsigned long gen_before = t->gen_before;
    unsigned long tid_before = t->tid_before;
    bool running_before = t->running_before;
    int epfd_before = t->epfd_before;

    char dt[DT_LOG_SIZE];
    uint64_t cid = get_new_cid();

    worker_role_t role = w->role;
    pthread_t *threads = (role == WR_REPLICA) ? worker_threads_upper : worker_threads_lower;
    pthread_mutex_t *mutex = (role == WR_REPLICA) ? &worker_mutex_upper : &worker_mutex_lower;

    if (!threads) {
        fprintf(stderr,
                "%s ERROR [MONITOR=%015lu] Thread pool is NULL i=%d role=%d "
                "-> skip migrate/reinit (stay quarantined)\n",
                curr_dt(dt), cid, i, (int)role);
        goto out;
    }

    // --- карантин уже установлен в monitor_thread ---
    if (epfd_before > 0) {
        close(epfd_before);
        w->epoll_fd = 0;
        fprintf(stderr, "%s INFO [MONITOR=%015lu] Worker epoll closed i=%d old=%d new=%d\n",
                curr_dt(dt), cid, i, epfd_before, w->epoll_fd);
    }

    // Если нет thread handle — НЕЛЬЗЯ мигрировать клиентов (иначе UAF)
    if (!th_before) {
        fprintf(stderr,
                "%s ERROR [MONITOR=%015lu] Found th=NULL i=%d gen=%lu TID=%lu running=%d self=%p "
                "-> skip migrate/reinit (stay quarantined)\n",
                curr_dt(dt), cid, i, gen_before, tid_before,
                (int)atomic_load(&w->running), (void*)self_before);
        goto out;
    }

    // Проверка на рассинхронизацию worker_threads[i] и worker->self
    if (self_before &&
        !pthread_equal(th_before, self_before)) {
        fprintf(stderr,
                "%s ERROR [MONITOR=%015lu] Handle MISMATCH i=%d gen=%lu: "
                "worker_threads[i]=%p, worker->self=%p, TID=%lu running=%d "
                "-> skip migrate/reinit (stay quarantined)\n",
                curr_dt(dt), cid, i, gen_before,
                (void*)th_before, (void*)self_before,
                tid_before, (int)running_before);
        goto out;
    }

    // проверяем, что handle не поменялся между снимком и сейчас
    pthread_mutex_lock(mutex);
    pthread_t th_now = threads[i];
    pthread_mutex_unlock(mutex);
    if (th_now != th_before) {
        fprintf(stderr,
                "%s ERROR [MONITOR=%015lu] Thread CHANGED i=%d th_before=%p th_now=%p gen=%lu TID=%lu self=%p "
                "-> skip migrate/reinit\n",
                curr_dt(dt), cid, i,
                (void*)th_before, (void*)th_now,
                gen_before, tid_before, (void*)self_before);
        goto out;
    }

    fprintf(stderr,
            "%s WARN [MONITOR=%015lu] JOIN begin i=%d th=%p gen=%lu TID=%lu self=%p\n",
            curr_dt(dt), cid, i, (void*)th_before, gen_before, tid_before, (void*)self_before);

    atomic_store(&w->ready_to_migrate, false);
    void *ret = NULL;
    int jrc = pthread_join(th_before, &ret);
    pthread_t self_after = atomic_load(&w->self);
    fprintf(stderr,
            "%s WARN [MONITOR=%015lu] JOIN end i=%d th=%p rc=%d ret=%p gen=%lu "
            "tid(before)=%lu tid(now)=%lu running(now)=%d self(now)=%p\n",
            curr_dt(dt), cid, i, (void*)th_before, jrc, ret,
            gen_before, tid_before,
            atomic_load(&w->os_tid),
            (int)atomic_load(&w->running),
            (void*)self_after);

    if (jrc != 0) {
        fprintf(stderr,
                "%s ERROR [MONITOR=%015lu] Failed pthread_join i=%d rc=%d -> skip migrate/reinit (stay quarantined)\n",
                curr_dt(dt), cid, i, jrc);
        goto out;
    }

    // важно: после join поток точно умер, но дополнительно проверяем маркеры
    if (atomic_load(&w->running)) {
        fprintf(stderr,
                "%s INFO [MONITOR=%015lu] Thread join OK but running=true i=%d gen=%lu tid(now)=%lu self(now)=%p\n",
                curr_dt(dt), cid, i, gen_before,
                atomic_load(&w->os_tid),
                (void*)w->self);
        // continue;
    }

    // зануляем handle
    pthread_mutex_lock(mutex);
    threads[i] = (pthread_t)0;
    pthread_mutex_unlock(mutex);

    fprintf(stderr, "%s WARN [MONITOR=%015lu] MIGRATE begin i=%d gen=%lu\n", curr_dt(dt), cid, i, gen_before);
    close_all_clients_for_worker_pools(w, i, cid);
    fprintf(stderr, "%s WARN [MONITOR=%015lu] MIGRATE done i=%d gen=%lu\n", curr_dt(dt), cid, i, gen_before);

    // реинит
    role = w->role;
    init_worker(w, role, cid);
    // после init_worker gen уже увеличился
    const unsigned long gen_after = atomic_load(&w->gen);
    fprintf(stderr,
            "%s WARN [MONITOR=%015lu] REINIT done i=%d role=%d gen %lu->%lu epfd=%d\n",
            curr_dt(dt), cid, i, (int)role,
            gen_before, gen_after, w->epoll_fd);

    // держим карантин до старта
    atomic_store(&w->is_quarantined, true);

    pthread_t new_th = (pthread_t)0;
    int prc = pthread_create(&new_th, NULL, worker_run, w);
    if (prc != 0) {
        fprintf(stderr,
                "%s ERROR [MONITOR=%015lu] Restart pthread_create failed i=%d rc=%d -> stay quarantined\n",
                curr_dt(dt), cid, i, prc);
        goto out;
    }

    pthread_mutex_lock(mutex);
    threads[i] = new_th;
    pthread_mutex_unlock(mutex);

    // снимаем карантин только после того, как worker_run реально запишет running=true
    for (int spin = 0; spin < 1000; ++spin) {
        if (atomic_load(&w->running)) break;
        sched_yield();
    }

    atomic_store(&w->is_quarantined, false);
    fprintf(stderr,
            "%s INFO [MONITOR=%015lu] RESTART ok i=%d role=%d new_th=%p gen=%lu TID=%lu running=%d epfd=%d self=%p\n",
            curr_dt(dt), cid, i, (int)role, (void*)new_th,
            atomic_load(&w->gen), atomic_load(&w->os_tid),
            (int)atomic_load(&w->running), w->epoll_fd,
            (void*)w->self);

out:
    free(t);
    return NULL;
}

void shrink_pool(target_half_t half, uint64_t cid) {
    if (!pool_shrink_idle_sec) return;

    pthread_mutex_t *mutex = (half == TARGET_LOWER_HALF) ? &worker_mutex_lower : &worker_mutex_upper;
    _Atomic int *countp = (half == TARGET_LOWER_HALF) ? &worker_count_lower : &worker_count_upper;
    const char *label = (half == TARGET_UPPER_HALF) ? "UPPER" : "LOWER";
    worker_t *pool = (half == TARGET_LOWER_HALF) ? workers_lower : workers_upper;
    pthread_t *threads = (half == TARGET_LOWER_HALF) ? worker_threads_lower : worker_threads_upper;
    _Atomic unsigned long *empty_since = (half == TARGET_LOWER_HALF) ? empty_since_ns_lower : empty_since_ns_upper;

    const int min_workers = (half == TARGET_LOWER_HALF)
                            ? initial_worker_count_lower
                            : initial_worker_count_upper;

    if (!pool || !threads || !empty_since) return;

    char dt[DT_LOG_SIZE];
    unsigned long now = nsecs_now();
    unsigned long last = atomic_load(&last_shrink_ns_half[half]);
    if (now - last < SHRINK_COOLDOWN_NS) return;

    pthread_mutex_lock(mutex);

    int wc = atomic_load(countp);
    if (wc <= min_workers) {
        pthread_mutex_unlock(mutex);
        return;
    }

    int i = wc - 1;
    worker_t *w = &pool[i];

    int nc = atomic_load(&w->num_clients);
    unsigned at = atomic_load(&w->active_tasks);
    bool quarantined = atomic_load(&w->is_quarantined);

    if (nc || at || quarantined) {
        atomic_store(&empty_since[i], 0ul);
        pthread_mutex_unlock(mutex);
        return;
    }

    unsigned long since = atomic_load(&empty_since[i]);
    if (!since) {
        atomic_store(&empty_since[i], now);

        fprintf(stderr,
                "%s INFO [POOL=%015lu] shrink candidate half=%s W[%d] empty_since=start wc=%d initial=%d\n",
                curr_dt(dt), cid, label, i, wc, min_workers);

        pthread_mutex_unlock(mutex);
        return;
    }

    unsigned long need_ns = (unsigned long)pool_shrink_idle_sec * 1000000000ul;
    unsigned long idle_ns = now - since;

    if (idle_ns < need_ns) {
        pthread_mutex_unlock(mutex);
        return;
    }

    /*
     * Anti-ping-pong guard:
     * Не удаляем пустой tail, если после его удаления оставшийся пул сразу
     * станет горячим по тем же признакам, которые запускают expand.
     */
    {
        int current=0, busy=0, near_full=0, free_slots=0;
        pool_aggregates_range_pools(half, 0, wc, &current, &busy, &near_full, &free_slots);

        /*
         * Tail уже проверен как пустой:
         *   nc == 0
         *   at == 0
         * значит после удаления:
         *   current - 1
         *   busy не меняется
         *   near_full не меняется
         *   free_slots - INITIAL_CLIENT_CAPACITY
         */
        int near_full_after = near_full;
        int free_slots_after = free_slots - INITIAL_CLIENT_CAPACITY;
        int current_after = current - 1;
        int busy_after = busy;

        if (current_after <= 0) {
            pthread_mutex_unlock(mutex);
            return;
        }

        int min_safe_slots_after = (current_after * INITIAL_CLIENT_CAPACITY) / 50;
        if (min_safe_slots_after < 32) min_safe_slots_after = 32;

        if (free_slots_after < 0) free_slots_after = 0;
        int busy_ppm_after = (busy_after * 1000) / current_after;

        if (busy_ppm_after >= TH_SHRINK_BUSY_MAX_PPM ||
            near_full_after * 100 >= current_after * TH_NEARFULL_MODERATE_FR ||
            free_slots_after <= min_safe_slots_after) {

            fprintf(stderr,
                    "%s INFO [POOL=%015lu] shrink skip half=%s W[%d]: anti-ping-pong "
                    "wc=%d current=%d busy=%d nf=%d free=%d -> after current=%d busy=%d(%dppm) nf=%d free=%d min_safe=%d\n",
                    curr_dt(dt), cid, label, i,
                    wc,
                    current, busy, near_full, free_slots,
                    current_after, busy_after, busy_ppm_after,
                    near_full_after, free_slots_after, min_safe_slots_after);

            atomic_store(&empty_since[i], 0ul);
            pthread_mutex_unlock(mutex);
            return;
        }
    }

    pthread_t th = threads[i];
    pthread_t self = atomic_load(&w->self);
    unsigned long gen = atomic_load(&w->gen);
    unsigned long tid = atomic_load(&w->os_tid);
    bool running = atomic_load(&w->running);
    int epfd = w->epoll_fd;

    if (!th) {
        fprintf(stderr,
                "%s WARN [POOL=%015lu] shrink skip half=%s W[%d]: thread handle is NULL wc=%d initial=%d epfd=%d running=%d self=%p tid=%lu\n",
                curr_dt(dt), cid, label, i, wc, min_workers,
                epfd, (int)running, (void*)self, tid);
        atomic_store(&empty_since[i], 0ul);
        pthread_mutex_unlock(mutex);
        return;
    }

    if (self && !pthread_equal(th, self)) {
        fprintf(stderr,
                "%s WARN [POOL=%015lu] shrink skip half=%s W[%d]: thread handle mismatch th=%p self=%p gen=%lu tid=%lu running=%d\n",
                curr_dt(dt), cid, label, i,
                (void*)th, (void*)self,
                gen, tid, (int)running);
        atomic_store(&empty_since[i], 0ul);
        pthread_mutex_unlock(mutex);
        return;
    }

    // Не останавливаем поток, ещё не прошедший стартовый барьер карантина.
    if (!atomic_load(&w->ready_to_epoll)) {
        atomic_store(&empty_since[i], 0ul);
        pthread_mutex_unlock(mutex);
        return;
    }

    // Закрываем worker от новых регистраций.
    atomic_store(&w->is_quarantined, true);

    // Финальная проверка пустоты уже после quarantine.
    pthread_mutex_lock(&w->clients_lock);

    nc = atomic_load(&w->num_clients);
    at = atomic_load(&w->active_tasks);

    if (nc || at) {
        pthread_mutex_unlock(&w->clients_lock);

        atomic_store(&w->is_quarantined, false);
        atomic_store(&empty_since[i], 0ul);

        fprintf(stderr,
                "%s INFO [POOL=%015lu] shrink abort half=%s W[%d]: became non-empty nc=%d active=%u\n",
                curr_dt(dt), cid, label, i, nc, at);

        pthread_mutex_unlock(mutex);
        return;
    }

    pthread_mutex_unlock(&w->clients_lock);

    int wake = -1;
    fprintf(stderr,
            "%s WARN [POOL=%015lu] shrink begin half=%s W[%d] wc=%d->%d initial=%d idle=%lus epfd=%d th=%p gen=%lu tid=%lu running=%d\n",
            curr_dt(dt), cid, label, i,
            wc, wc - 1, min_workers,
            idle_ns / 1000000000ul,
            epfd, (void*)th,
            gen, tid, (int)running);

    if (epfd > 0) {
        struct epoll_event wake_ev;
        memset(&wake_ev, 0, sizeof(wake_ev));
        wake_ev.data.ptr = NULL;
        wake_ev.events = EPOLLIN;

        wake = eventfd(0, EFD_NONBLOCK | EFD_CLOEXEC);
        if (wake < 0) {
            fprintf(stderr,
                    "%s ERROR [POOL=%015lu] shrink wake eventfd failed half=%s W[%d] errno=%d (%s)\n",
                    curr_dt(dt), cid, label, i, errno, strerror(errno));

            atomic_store(&w->is_quarantined, false);
            atomic_store(&w->ready_to_migrate, false);
            atomic_store(&empty_since[i], 0ul);

            pthread_mutex_unlock(mutex);
            return;
        }

        if (epoll_ctl(epfd, EPOLL_CTL_ADD, wake, &wake_ev) < 0) {
            fprintf(stderr,
                    "%s ERROR [POOL=%015lu] shrink wake epoll_ctl ADD failed half=%s W[%d] epfd=%d wake_fd=%d errno=%d (%s)\n",
                    curr_dt(dt), cid, label, i, epfd, wake, errno, strerror(errno));

            close(wake);

            atomic_store(&w->is_quarantined, false);
            atomic_store(&w->ready_to_migrate, false);
            atomic_store(&empty_since[i], 0ul);

            pthread_mutex_unlock(mutex);
            return;
        }
    }

    atomic_store(&w->ready_to_migrate, true);

    if (wake >= 0) {
        ssize_t wr;
        uint64_t one = 1;
        do {
            wr = write(wake, &one, sizeof(one));
        } while (wr < 0 && errno == EINTR);
        if (wr != (ssize_t)sizeof(one) && errno != EAGAIN) {
            fprintf(stderr,
                    "%s WARN [POOL=%015lu] shrink wake write failed half=%s W[%d] wake_fd=%d errno=%d (%s)\n",
                    curr_dt(dt), cid, label, i, wake, errno, strerror(errno));
        }
    }

    void *ret = NULL;
    // Ждём парковки либо выхода worker до установки ready_to_migrate.
    while (!atomic_load(&w->migrate_parked) && atomic_load(&w->running)) {
        sched_yield();
    }

    // Освобождаем парковку; завершение потока подтверждается штатным join.
    atomic_store(&w->ready_to_migrate, false);

    int jrc = pthread_join(th, &ret);
    if (jrc != 0) {
        fprintf(stderr,
                "%s ERROR [POOL=%015lu] shrink join failed half=%s W[%d] rc=%d -> stay quarantined wc=%d\n",
                curr_dt(dt), cid, label, i, jrc, wc);

        if (wake >= 0)
            close(wake);

        atomic_store(&last_shrink_ns_half[half], nsecs_now());
        pthread_mutex_unlock(mutex);
        return;
    }

    if (wake >= 0)
        close(wake);

    threads[i] = (pthread_t)0;

    int epfd_now = atomic_exchange(&w->epoll_fd, 0);
    if (epfd_now > 0) {
        close(epfd_now);
    }

    atomic_store(&w->running, false);
    atomic_store(&w->os_tid, 0ul);
    atomic_store(&w->self, (pthread_t)0);
    atomic_store(&w->active_tasks, 0u);
    atomic_store(&w->ready_to_migrate, false);
    atomic_store(&w->ready_to_epoll, false);
    atomic_store(&w->migrate_parked, false);
    atomic_store(&empty_since[i], 0ul);

    // Слот выходит за пределы [0, worker_count), поэтому quarantine может остаться любым.
    // Но лучше оставить true до следующего init_worker(), чтобы слот не выглядел готовым при отладке.
    atomic_store(&w->is_quarantined, true);

    atomic_store(countp, wc - 1);
    atomic_store(&last_shrink_ns_half[half], nsecs_now());

    fprintf(stderr,
        "%s WARN [POOL=%015lu] shrink done half=%s W[%d] wc=%d->%d gen=%lu ret=%p epfd_after=%d\n",
        curr_dt(dt), cid, label, i,
        wc, wc - 1,
        atomic_load(&w->gen), ret,
        atomic_load(&w->epoll_fd));

    pthread_mutex_unlock(mutex);
}

void* monitor_pools(void *arg) {
    (void)arg;
    char dt[DT_LOG_SIZE];
    uint64_t cid = get_new_cid();

    for (;;) {
        const unsigned long now = now_monotonic_ns();

        for (int p = 0; p < 2; ++p) {
            const target_half_t half = (p == 0) ? TARGET_LOWER_HALF : TARGET_UPPER_HALF;
            worker_t *pool = (half == TARGET_LOWER_HALF) ? workers_lower : workers_upper;
            pthread_t *ths = (half == TARGET_LOWER_HALF) ? worker_threads_lower : worker_threads_upper;
            pthread_mutex_t *mutex = (half == TARGET_LOWER_HALF) ? &worker_mutex_lower : &worker_mutex_upper;
            const int limit = (half == TARGET_LOWER_HALF)
                            ? atomic_load(&worker_count_lower)
                            : atomic_load(&worker_count_upper);

            if (!pool || !ths) continue;

            for (int i = 0; i < limit; ++i) {
                worker_t *w = &pool[i];
                pthread_mutex_lock(mutex);
                pthread_t th = ths[i]; // то, что монитор считает handle воркера
                pthread_t self = atomic_load(&w->self); // то, что сам воркер записал в worker->self
                pthread_mutex_unlock(mutex);

                if (atomic_load(&w->is_quarantined)) continue;

                const unsigned at0 = atomic_load(&w->active_tasks);
                if (!at0) continue;

                const unsigned long last0 = atomic_load(&w->last_progress_ns);
                if (now < last0) continue;

                const unsigned long diff_s0 = (now - last0) / 1000000000lu;
                if (w->role == WR_CLIENT && diff_s0 < worker_client_idle_timeout) continue;
                if (w->role == WR_REPLICA && diff_s0 < worker_replica_idle_timeout) continue;

                const int nc0 = w->num_clients; // эвристика
                if (!nc0) continue;

                // повторная проверка чтобы не стрелять в оживший воркер
                const unsigned long last1 = atomic_load(&w->last_progress_ns);
                const unsigned at1 = atomic_load(&w->active_tasks);
                if (!at1) continue;
                const unsigned long diff_s1 = (now >= last1) ? ((now - last1) / 1000000000lu) : 0;
                if (w->role == WR_CLIENT && diff_s1 < worker_client_idle_timeout) continue;
                if (w->role == WR_REPLICA && diff_s1 < worker_replica_idle_timeout) continue;

                // --- фиксируем снимок идентификаторов ---
                const unsigned long gen = atomic_load(&w->gen);
                const unsigned long tid = atomic_load(&w->os_tid);
                const bool running = atomic_load(&w->running);
                const int epfd = w->epoll_fd;

                fprintf(stderr,
                        "%s WARN [MONITOR=%015lu] STALL i=%d w=%p role=%d gen=%lu TID=%lu running=%d "
                        "th[%d]=%p epfd=%d nc=%d at=%u diff=%lus, r2m=%d, r2e=%d\n",
                        curr_dt(dt), cid, i, (void*)w, (int)w->role,
                        gen, tid, (int)running,
                        i, (void*)th,
                        epfd, nc0, at1, diff_s1,
                        atomic_load(&w->ready_to_migrate),
                        atomic_load(&w->ready_to_epoll));

                // --- карантин ---
                atomic_store(&w->is_quarantined, true);
                usleep(100000);
                atomic_store(&w->ready_to_migrate, true);
                usleep(100000);

                if (atomic_load(&w->ready_to_epoll)) {
                    atomic_store(&w->is_quarantined, false);
                    atomic_store(&w->ready_to_migrate, false);
                    fprintf(stderr,
                        "%s INFO [MONITOR=%015lu] False stall i=%d w=%p role=%d gen=%lu TID=%lu running=%d th[%d]=%p epfd=%d\n",
                        curr_dt(dt), cid, i, (void*)w, (int)w->role,
                        gen, tid, (int)running,
                        i, (void*)th, epfd);
                    continue;
                }

                rescue_all_clients_pools(w, i);

                // Всё, что было дальше (epoll close, join, migrate, reinit, restart)
                // переносим в отдельный тред, чтобы монитор не блокировался.
                monitor_quarantine_task_t *task =
                    (monitor_quarantine_task_t*)malloc(sizeof(*task));
                if (!task) {
                    fprintf(stderr,
                            "%s ERROR [MONITOR=%015lu] Quarantine task alloc failed i=%d "
                            "-> stay quarantined (no join/migrate/reinit)\n",
                            curr_dt(dt), cid, i);
                    // воркер останется в карантине, монитор продолжит работу
                    continue;
                }

                pthread_t helper;
                task->worker = w;
                task->index = i;
                task->epfd_before = epfd;
                task->running_before = running;
                task->gen_before = gen;
                task->tid_before = tid;
                task->self_before = self;
                task->th_before = th;

                int hrc = pthread_create(&helper, NULL, monitor_quarantine_worker_pools, task);
                if (hrc != 0) {
                    fprintf(stderr,
                            "%s ERROR [MONITOR=%015lu] Quarantine thread create failed i=%d rc=%d "
                            "-> stay quarantined (no join/migrate/reinit)\n",
                            curr_dt(dt), cid, i, hrc);
                    free(task);
                    continue;
                }
                pthread_detach(helper);
                // Ничего больше с этим воркером в этом проходе не делаем.
            }
        }

        struct timespec ts = { .tv_sec = 0, .tv_nsec = 300000000 };
        try_expand_pool_pools(false, cid);
        shrink_pool(TARGET_LOWER_HALF, cid);
        shrink_pool(TARGET_UPPER_HALF, cid);

        nanosleep(&ts, NULL);
    }

    return NULL;
}

