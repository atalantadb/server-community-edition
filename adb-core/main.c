static inline int rearm_epoll(worker_t* w, connection_t* c, uint32_t events) {
    struct epoll_event ev;
    ev.data.ptr = c;
    ev.events   = events | EPOLLONESHOT;  // всегда ONESHOT
    return epoll_ctl(w->epoll_fd, EPOLL_CTL_MOD, transport_fd(&c->transport), &ev);
}

