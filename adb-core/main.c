static inline unsigned long now_monotonic_ns(void) {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (unsigned long)ts.tv_sec * 1000000000ull + (unsigned long)ts.tv_nsec;
}

static inline int find_free_worker_slot_pools(target_half_t half) {
    worker_t *pool = (half == TARGET_LOWER_HALF) ? workers_lower : workers_upper;
    int limit = (half == TARGET_LOWER_HALF)
              ? atomic_load(&worker_count_lower)
              : atomic_load(&worker_count_upper);

    if (!pool) return limit;

    for (int i = 0; i < limit; ++i) {
        // Слот считается свободным, если воркер не готов к работе
        // (epoll_fd не создан/закрыт или clients не выделен).
        if (pool[i].epoll_fd <= 0 && atomic_load(&pool[i].is_quarantined) == false) {
            return i;
        }
    }

    return limit; // свободных "дыр" нет — добавляем в хвост
}

static inline void detach_client_from_worker(worker_t *w, connection_t *c) {
    char dt[DT_LOG_SIZE];

    const uint64_t cli_cid = (w && c && c->t_handler) ? c->t_handler->cid : 0;
    int wi = -1;
    if (c) wi = c->owner_wi;

    pthread_mutex_lock(&w->clients_lock);

    int idx = (c ? c->owner_idx : -1);
    connection_t *before = NULL;

    if (idx >= 0 && idx < w->num_clients) {
        before = w->clients[idx];
    }

    if (c && idx >= 0 && idx < w->num_clients && w->clients[idx] == c) {
        fprintf(stderr,
            "%s DEBUG [DETACH=%015lu] w=%p(epoll=%d role=%s) slot=%d: %p -> NULL | "
            "conn=%p(fd=%d) owner(%d,%d) -> (-1,-1)\n",
            curr_dt(dt), cli_cid, (void*)w, w->epoll_fd, safe_role_str(w->role),
            idx, (void*)before, (void*)c, transport_fd(&c->transport), c->owner_wi, c->owner_idx);

        w->clients[idx] = NULL;

        // сжать хвост, чтобы num_clients не рос бесконечно
        while (w->num_clients > 0 && w->clients[w->num_clients-1] == NULL)
            w->num_clients--;
    } else {
        // Полезно видеть странные detach’и
        fprintf(stderr,"%s WARN [DETACH=%015lu] skip: w=%p(epoll=%d role=%s) idx=%d num_clients=%d "
            "slot_ptr=%p expected_conn=%p | conn owner(%d,%d) fd=%d\n",
            curr_dt(dt), cli_cid,
            (void*)w, w->epoll_fd, safe_role_str(w->role),
            idx, w->num_clients,
            (void*)before, (void*)c,
            c ? c->owner_wi : -1, c ? c->owner_idx : -1,
            c ? transport_fd(&c->transport) : -1);
    }

    pthread_mutex_unlock(&w->clients_lock);

    if (c) {
        c->owner_idx = -1;
        c->owner_wi = -1;
    }
}



void init_worker(worker_t *worker, worker_role_t role, uint64_t cid) {
    char dt[DT_LOG_SIZE];
    if (log_level > 0)
        fprintf(stderr, "%s DEBUG [WORKER=%015lu] Enter init_worker worker=%p, role=%d\n",
            curr_dt(dt), cid, (void*)worker, (int) role);

    atomic_store(&worker->role, role);

    // (1) epoll — всегда новый дескриптор
    if (worker->epoll_fd > 0) {
        // На всякий случай закрываем старый epoll, если он остался открытым
        close(worker->epoll_fd);
        worker->epoll_fd = -1;
    }
    worker->epoll_fd = epoll_create1(0);
    if (worker->epoll_fd < 0) { perror("epoll_create1"); exit(EXIT_FAILURE); }

    // (2) Массив клиентов и мьютекс:
    // - если массив уже был — ПОВТОРНО его не аллоцируем и НЕ реинициализируем мьютекс
    // - если не был — создаём и инициализируем
    if (worker->clients == NULL) {
        // Новый воркер (первичная инициализация)
        worker->clients = (connection_t **)malloc(INITIAL_CLIENT_CAPACITY * sizeof(connection_t *));
        if (!worker->clients) { perror("malloc for clients"); exit(EXIT_FAILURE); }
        memset(worker->clients, 0, INITIAL_CLIENT_CAPACITY * sizeof(connection_t *));
        worker->num_clients = 0;

        // Мьютекс инициализируем только один раз при первичной инициализации
        if (pthread_mutex_init(&worker->clients_lock, NULL) != 0) {
            perror("pthread_mutex_init");
            exit(EXIT_FAILURE);
        }
    } else {
        // Повторное использование существующей структуры:
        // массив клиентов уже принадлежит воркеру — переиспользуем без доп. malloc/free
        // На этом этапе monitor/migration должны были освободить слоты.
        // Обнулим длину (слоты могли быть очищены ранее).
        pthread_mutex_lock(&worker->clients_lock);
        worker->num_clients = 0;
        // ВНИМАНИЕ: НЕ вызываем pthread_mutex_init повторно (без destroy) — это было бы UB.
        // При необходимости заполнения нулями — делаем это, но строго без гонок.
        memset(worker->clients, 0, INITIAL_CLIENT_CAPACITY * sizeof(connection_t *));
        pthread_mutex_unlock(&worker->clients_lock);
    }

    // (3) Метрики/флаги
    atomic_store(&worker->active_tasks, 0u);
    atomic_store(&worker->last_progress_ns, now_monotonic_ns());
    atomic_store(&worker->is_quarantined, false);
    atomic_store(&worker->ready_to_migrate, false);
    atomic_store(&worker->ready_to_epoll, false);
    atomic_store(&worker->migrate_parked, false);

    atomic_store(&worker->os_tid, 0ul);
    atomic_store(&worker->running, false);
    atomic_store(&worker->self, (pthread_t)0);
    atomic_fetch_add(&worker->gen, 1ul); // новое поколение слота

    if (log_level > 2)
        fprintf(stderr, "%s DEBUG [WORKER=%015lu] Done init_worker: epoll_fd=%d clients=%p cap=%d, TID=%lu\n",
            curr_dt(dt), cid, worker->epoll_fd, (void*)worker->clients, INITIAL_CLIENT_CAPACITY, worker->os_tid);
}


// сопоставление роли половине пула (для целевого расширения при нехватке)
static inline target_half_t half_for_role(worker_role_t role) {
    return (role == WR_REPLICA) ? TARGET_UPPER_HALF : TARGET_LOWER_HALF;
}

static int pick_worker_index_by_role_pools(worker_role_t role) {
    worker_t *pool = (role == WR_REPLICA) ? workers_upper : workers_lower;
    int limit = (role == WR_REPLICA)
              ? atomic_load(&worker_count_upper)
              : atomic_load(&worker_count_lower);

    unsigned best_at = UINT_MAX;
    int best_nc = INT_MAX;
    int idx = -1;

    if (!pool) return -1;

    for (int i = 0; i < limit; ++i) {
        worker_t *w = &pool[i];

        if (w->role != role) continue;
        if (atomic_load(&w->is_quarantined)) continue;
        if (w->epoll_fd <= 0 || w->clients == NULL || atomic_load(&w->is_quarantined) || w->self == 0) continue;

        int nc = w->num_clients;
        if (nc >= INITIAL_CLIENT_CAPACITY) continue;

        unsigned at = atomic_load(&w->active_tasks);
        if (at < best_at || (at == best_at && nc < best_nc)) {
            best_at = at; best_nc = nc; idx = i;
        }
    }

    return idx; // -1 если никого подходящего нет
}

void* client_handler_thread(void *arg) {
    char dt[DT_LOG_SIZE];
    connection_t *conn = (connection_t *)arg;
    if (!conn)
        pthread_exit(NULL);

    uint64_t cid = conn->t_handler->cid;
    int cli_fd = transport_fd(&conn->transport);
    pid_t tid = syscall(SYS_gettid);
    fprintf(stderr, "%s INFO [MAIN=%015lu] New client %d (socket=%d) from %s:%s, TID=%d\n",
            curr_dt(dt), cid, total_clients, cli_fd, conn->t_handler->ip, conn->t_handler->port, tid);

    if (!transport_accept_server(&conn->transport, cid)) {
        fprintf(stderr, "%s ERROR [MAIN=%015lu] TLS handshake for socket=%d failed, finish thread\n",
                curr_dt(dt), cid, cli_fd);
        close_conn(conn);
        free(conn);
        pthread_exit(NULL);
    }
    int auth_rc = 1;
    // Основной цикл обработки запросов клиента
    while (1) {
        if (atomic_load(&conn->state) == STATE_AUTH_PENDING)
            auth_rc = process_authentication(conn->t_handler);
        if (auth_rc <= 0) {
            fprintf(stderr, "%s WARN [MAIN=%015lu] Authentication failed for fd=%d, code=%d, closing\n",
                    curr_dt(dt), cid, cli_fd, auth_rc);
            if (conn->mode == BLOCKING_MODE) {
                close_conn(conn);
                free(conn);
                conn = NULL;
            }
            break;
        }
        atomic_store(&conn->state, STATE_AUTHENTICATED);
        int rc = recv_client_requests(conn);
        if (rc < 0) {
            if (rc == -8) {
                fprintf(stderr, "%s INFO [MAIN=%015lu] Stop processing requests on fd=%d, closing connection\n",
                    curr_dt(dt), cid, cli_fd);
            } else
                fprintf(stderr, "%s INFO [MAIN=%015lu] Stop processing requests with code=%d on fd=%d, closing connection\n",
                    curr_dt(dt), cid, rc, cli_fd);

            // Если мы оказались здесь, значит миграция не произошла,
            // и соединение должно быть корректно закрыто и очищено.
            if (conn->mode == BLOCKING_MODE) {
                close_conn(conn);
                free(conn);
                conn = NULL;
            }
            if (log_level > 0)
                fprintf(stderr, "%s INFO [MAIN=%015lu] Client thread closed conn->fd=%d\n", curr_dt(dt), cid, cli_fd);
            break;
        } else {
            break;
        }
    }
    fprintf(stderr, "%s INFO [MAIN=%015lu] Client thread exit\n", curr_dt(dt), cid);
    pthread_exit(NULL);
}



// ---------- Рабочий поток ----------------------------------------
void* worker_run(void *arg) {
    char dt[DT_LOG_SIZE];
    worker_t *worker = arg;
    uint64_t cid = get_new_cid();

    // Кто именно сейчас является worker_run для этого слота
    pthread_t self = pthread_self();
    atomic_store(&worker->self, self);

    pid_t tid = syscall(SYS_gettid);
    atomic_store(&worker->os_tid, (unsigned long)tid);
    atomic_store(&worker->running, true);

    fprintf(stderr,
            "%s INFO [WORKER=%015lu] START w=%p role=%d epoll_fd=%d pthread_self=%p TID=%lu gen=%lu\n",
            curr_dt(dt), cid,
            (void*)worker,
            (int)worker->role,
            worker->epoll_fd,
            (void*)self,
            (unsigned long)atomic_load(&worker->os_tid),
            atomic_load(&worker->gen));

    struct epoll_event evs[MAX_EVENTS];
    struct timespec ts;

    fprintf(stderr, "%s INFO [WORKER=%015lu] Worker thread started epoll_fd=%d, role=%d, is_quarantined=%u, ready_to_migrate=%u\n",
            curr_dt(dt), cid, worker->epoll_fd, worker->role, atomic_load(&worker->is_quarantined), atomic_load(&worker->ready_to_migrate));

    bool seen = false;
    while (atomic_load(&worker->is_quarantined)) {
        if (!seen) {
            fprintf(stderr, "%s INFO [WORKER=%015lu] Worker thread started epoll_fd=%d, is quarantined=%u, sleep a bit\n",
                curr_dt(dt), cid, worker->epoll_fd, atomic_load(&worker->is_quarantined));
            seen = true;
        }
        usleep(10000);
    }
    if (seen)
        fprintf(stderr, "%s INFO [WORKER=%015lu] Worker thread started epoll_fd=%d, is NOT quarantined=%u, continue\n",
            curr_dt(dt), cid, worker->epoll_fd, atomic_load(&worker->is_quarantined));

    for (;;) {
        if (atomic_load(&worker->ready_to_migrate)) {
            atomic_store(&worker->ready_to_epoll, false);
            atomic_store(&worker->migrate_parked, true);

            while (atomic_load(&worker->ready_to_migrate))
                usleep(100000);

            atomic_store(&worker->migrate_parked, false);

            fprintf(stderr, "%s INFO [WORKER=%015lu] Worker thread migrating, epoll_fd=%d, exit\n",
                curr_dt(dt), cid, worker->epoll_fd);
            break;
        }

        if (atomic_load(&worker->is_quarantined))
            break;

        atomic_store(&worker->ready_to_epoll, true);
        int n = epoll_wait(worker->epoll_fd, evs, MAX_EVENTS, -1);

        clock_gettime(CLOCK_REALTIME, &ts);
        if (n < 0) {
            if (errno == EINTR) continue;
            // ожидаемый сценарий при закрытом epoll: errno=EBADF, выходим из цикла
            fprintf(stderr,
                    "%s WARN [WORKER=%015lu] Epoll_wait failed epfd=%d errno=%d (%s) pthread_self=%p TID=%lu gen=%lu -> break\n",
                    curr_dt(dt), cid, worker->epoll_fd, errno, strerror(errno),
                    (void*)self, (unsigned long)atomic_load(&worker->os_tid),
                    atomic_load(&worker->gen));
            break;
        }

        atomic_store(&worker->last_progress_ns, now_monotonic_ns());
        atomic_store(&worker->ready_to_epoll, false);

        for (int i = 0; i < n; i++) {
            if (atomic_load(&worker->is_quarantined)) break;

            uint32_t ev = evs[i].events;
            connection_t *conn = (connection_t *) evs[i].data.ptr;
            if (!conn || atomic_load(&conn->state) == STATE_FREED) continue;
            atomic_store(&conn->migrate_count, 0);
            atomic_store(&conn->t_handler->recv_ts, ts.tv_sec * 1000L);

            // Метрики: воркер взял «квант» работы и коннект в обработку
            atomic_fetch_add(&worker->active_tasks, 1u);
            atomic_fetch_add(&conn->in_processing, 1);

            int closed = 0;
            uint32_t next = EPOLLIN | EPOLLRDHUP; // по умолчанию ждём чтение

            // Быстрые ошибки/закрытия
            if (ev & (EPOLLERR | EPOLLHUP | EPOLLRDHUP)) {
                if (log_level > 2)
                    fprintf(stderr, "%s INFO [WORKER=%015lu] Worker epoll_fd=%d, ERR/HUP/RDHUP fd=%d -> close\n",
                            curr_dt(dt), cid, worker->epoll_fd, transport_fd(&conn->transport));
                epoll_ctl(worker->epoll_fd, EPOLL_CTL_DEL, transport_fd(&conn->transport), NULL);
                detach_client_from_worker(worker, conn);
                close_conn(conn);
                free(conn);
                conn = NULL;
                atomic_fetch_sub(&worker->active_tasks, 1u);
                continue;
            }

            // EPOLLIN обработка
            if (ev & EPOLLIN) {
                if (atomic_load(&conn->state) == STATE_AUTH_PENDING) {
                    int ar = process_authentication(conn->t_handler);
                    if (ar == 1) {
                        atomic_store(&conn->state, STATE_AUTHENTICATED);
                        pid_t tid2 = syscall(SYS_gettid);
                        fprintf(stderr, "%s INFO [WORKER=%015lu] fd=%d authenticated, TID=%u\n",
                                curr_dt(dt), cid, transport_fd(&conn->transport), tid2);
                        conn->worker = worker;
                        next = EPOLLIN | EPOLLRDHUP;
                    } else if (ar == 0) {
                        next = EPOLLIN | EPOLLRDHUP; // ждать ещё чтение
                    } else if (ar == -2) {
                        next = EPOLLOUT | EPOLLRDHUP; // ждать возможность записи
                    } else {
                        fprintf(stderr, "%s WARN [WORKER=%015lu] Access failed fd=%d code=%d -> close\n",
                                curr_dt(dt), cid, transport_fd(&conn->transport), ar);
                        epoll_ctl(worker->epoll_fd, EPOLL_CTL_DEL, transport_fd(&conn->transport), NULL);
                        detach_client_from_worker(worker, conn);
                        close_conn(conn);
                        free(conn);
                        conn = NULL;
                        closed = 1;
                    }
                } else if (atomic_load(&conn->state) == STATE_AUTHENTICATED) {
                    int ret = recv_client_requests(conn);
                    if (ret == 0) {
                        next = EPOLLIN | EPOLLRDHUP; // читать дальше
                    } else if (ret == -2) {
                        next = EPOLLOUT | EPOLLRDHUP; // ждать запись
                    } else if (ret < 0) {
                        fprintf(stderr, "%s WARN [WORKER=%015lu] Worker epoll_fd=%d ret=%d fd=%d -> close\n",
                                curr_dt(dt), cid, worker->epoll_fd, ret, transport_fd(&conn->transport));
                        epoll_ctl(worker->epoll_fd, EPOLL_CTL_DEL, transport_fd(&conn->transport), NULL);
                        detach_client_from_worker(worker, conn);
                        close_conn(conn);
                        free(conn);
                        conn = NULL;
                        closed = 1;
                    } else {
                        // ret > 0: запрос обработан — снова ждём входящие
                        next = EPOLLIN | EPOLLRDHUP;
                    }
                }
            }

            // EPOLLOUT обработка (дозапись ответа / WANT_WRITE)
            if (!closed && (ev & EPOLLOUT)) {
                int ret = recv_client_requests(conn);
                if (ret == -2) {
                    next = EPOLLOUT | EPOLLRDHUP; // всё ещё ждём запись
                } else if (ret < 0) {
                    epoll_ctl(worker->epoll_fd, EPOLL_CTL_DEL, transport_fd(&conn->transport), NULL);
                    detach_client_from_worker(worker, conn);
                    close_conn(conn);
                    free(conn);
                    conn = NULL;
                    closed = 1;
                } else {
                    // дозаписали/обработали — возвращаемся к чтению
                    next = EPOLLIN | EPOLLRDHUP;
                }
            }

            // Реарм, если соединение живо
            if (!closed && atomic_load(&conn->state) != STATE_FREED) {
                if (!atomic_load(&worker->is_quarantined)) {
                    if (rearm_epoll(worker, conn, next) < 0) {
                        perror("epoll_ctl MOD (rearm)");
                        epoll_ctl(worker->epoll_fd, EPOLL_CTL_DEL, transport_fd(&conn->transport), NULL);
                        detach_client_from_worker(worker, conn);

                        atomic_fetch_sub(&conn->in_processing, 1);
                        atomic_fetch_sub(&worker->active_tasks, 1u);
                        close_conn(conn);
                        free(conn);
                        conn = NULL;
                        // И после этого уже не нужно второй раз трогать conn->in_processing в хвосте
                        continue;
                    }
                }
            }

            // Сняли флаги занятий
            atomic_fetch_sub(&worker->active_tasks, 1u);
            if (conn)
                atomic_fetch_sub(&conn->in_processing, 1);
        }
    }

    fprintf(stderr,
            "%s INFO [WORKER=%015lu] STOP w=%p role=%d epoll_fd=%d pthread_self=%p TID=%lu gen=%lu\n",
            curr_dt(dt), cid, (void*)worker, (int)worker->role, worker->epoll_fd,
            (void*)self, atomic_load(&worker->os_tid), atomic_load(&worker->gen));

    // маркеры жизни потока
    atomic_store(&worker->running, false);
    atomic_store(&worker->os_tid, 0ul);
    atomic_store(&worker->self, (pthread_t)0);

    fprintf(stderr, "%s INFO [WORKER=%015lu] Worker thread done, epoll_fd=%d\n",
        curr_dt(dt), cid, worker->epoll_fd);
    return NULL;
}

