uint32_t index_put(struct region_info_t *r_info, msg_cli_t *msg_cli, uint8_t *buff, table_handler_t *t_handler, uint8_t bs, bool no_insert_coll) {
    char dt[DT_LOG_SIZE];
    uint8_t b = r_info->r_idx_b[bs]->idx_r_help->b;
    uint32_t k_idx = r_info->r_idx_b[bs]->idx_r_help->k_idx;
    int32_t result;

    if (k_idx <= r_info->r_idx_b[bs]->f_idx_size[b]) {
        if (r_info->r_idx_b[bs]->idx[b][k_idx].o_index == 0 && msg_cli->type == MSG_PUT) {
            if (log_level > 3 || r_info->log_level > 3)
                fprintf(stderr, "%s TRACE [RS_IDX=%015lu] Ready to insert msg_size=%u, bs=%d, b_offset=%u\n", curr_dt(dt), t_handler->cid, msg_cli->msg_size, bs,
                        r_info->r_idx_b[bs]->b_offset[b]);
            result = insert(r_info, msg_cli, buff, t_handler, true, -1, -1, 0, bs);
            r_info->r_idx_b[bs]->f_idx_curr_size[b]++;

            if (result == INSERT_TOO_BIG) {
                del_from_index(r_info, r_info->r_idx_b[bs]->idx[b][k_idx].o_index, msg_cli, t_handler, -1, bs);

                if (log_level > 2 || r_info->log_level > 3)
                    fprintf(stderr, "%s TRACE [RS_IDX=%015lu] Insert too BIG msg_size=%u, bs=%d, k_idx=%u\n", curr_dt(dt), t_handler->cid, msg_cli->msg_size, bs, k_idx);
            } else {
                if (r_info->r_idx_b[bs]->f_idx_size[b] < pow(2, 16))
                    r_info->r_idx_b[bs]->k1_index[b][k_idx] = r_info->r_idx_b[bs]->idx_r_help->k1;

                if (r_info->r_idx_b[bs]->f_idx_size[b] < pow(2, 24))
                    r_info->r_idx_b[bs]->k2_index[b][k_idx] = r_info->r_idx_b[bs]->idx_r_help->k2;
                r_info->r_idx_b[bs]->idx[b][k_idx].k3_index = r_info->r_idx_b[bs]->idx_r_help->k3;
                maybe_start_index_resize(r_info, b, bs, t_handler);
            }
            return result;
        } else {
            uint32_t read_block = r_info->r_idx_b[bs]->idx[b][k_idx].o_index;
            result = get_put(r_info, read_block, msg_cli, buff, t_handler, -1, bs);

            if (result == RECORD_TOO_LARGE_RESULT)
                return RECORD_TOO_LARGE_RESULT;

            if (result == GET_PUT_EXTRACT_ERROR)
                finish_thread(r_info, 70, true, t_handler);

            if (log_level > 3 || r_info->log_level > 3)
                fprintf(stderr, "%s TRACE [RS_IDX=%015lu] Done get or update msg_size=%u, update_status=%d, bs=%d, read_block=%u, z=%d\n", curr_dt(dt), t_handler->cid,
                        msg_cli->msg_size, result, bs, read_block, r_info->r_idx_b[bs]->idx[b][read_block].z_index);

            if (t_handler->realloc_buff && msg_cli->lob_info != 2)
                buff = t_handler->buff;

            if (t_handler->realloc_big_buff && msg_cli->lob_info != 2)
                buff = t_handler->big_buff;

            if (result == UPDATE_OK) {
                maybe_start_index_resize(r_info, b, bs, t_handler);
                return UPDATE_OK;
            }

            if (result == UPDATE_TOO_BIG)
                return UPDATE_TOO_BIG;

            if (result == UPDATE_COLLISION) {
                int res = get_upd_coll(r_info, msg_cli, buff, t_handler, bs, no_insert_coll, k_idx);

                if (res == GET_PUT_EXTRACT_ERROR)
                    finish_thread(r_info, 70, true, t_handler);

                if (res == UPDATE_OK || res == INSERT_OK)
                    maybe_start_index_resize(r_info, b, bs, t_handler);
                return res;
            }
        }
    } else {
        // TODO resize
        char dt[DT_LOG_SIZE];
        fprintf(stderr, "%s ERROR [RS_IDX=%015lu] Error code 115 idx.oc_index size exceed\n", curr_dt(dt), t_handler->cid);
        finish_thread(r_info, 115, true, t_handler);
        ;
    }
    finish_thread(r_info, 41, true, t_handler);
}
