static uint32_t make_delete_marker(uint8_t *dst, const uint8_t *record, const disk_record_header_t *header, uint64_t version) {
    uint32_t size = header->qv_offset;

    if (size > FIX_USEFUL_BLOCK_SIZE || version == 0)
        return 0;
    memcpy(dst, record, size);
    record_header_store_le(dst, size, 4);
    dst[MSG_TYPE_OFFSET] = MSG_PUT;
    dst[13] = dst[14] = dst[15] = 0;
    record_header_store_le(dst + QV_SIZE_RECORD_OFFSET, 0, 4);

    if (!disk_record_version_write(dst, size, version))
        return 0;
    return size;
}

static int fresh_put_has_values(const uint8_t *buff, const msg_cli_t *msg) {
    uint64_t start = DISK_RECORD_HEADER_SIZE + (uint64_t)msg->kv->key_size + msg->kv->cf_size;

    if (start > msg->msg_size)
        return -1;
    uint32_t at = (uint32_t)start;

    while (at < msg->msg_size) {
        if (msg->msg_size - at < TS_SIZE + 2U * sizeof(uint32_t))
            return -1;
        uint32_t qfl = (uint32_t)record_header_load_le(buff + at + TS_SIZE, 4);
        uint32_t value = (uint32_t)record_header_load_le(buff + at + TS_SIZE + 4, 4);
        at += TS_SIZE + 2U * sizeof(uint32_t);
        uint32_t name = qfl & UINT32_C(0x7fffffff);

        if (name > msg->msg_size - at || value > msg->msg_size - at - name)
            return -1;

        if (!(qfl & UINT32_C(0x80000000)))
            return 1;
        at += name + value;
    }
    return 0;
}

static bool publish_delete_marker(region_info_t *r, uint8_t *marker, uint32_t size, table_handler_t *th) {
    uint8_t bs = r->bs_map[BLOCK_ARRAY_LAST_POS];
    idx_region_info_t *idx = r->r_idx_b[bs];

    if (idx == NULL || idx->fd[FBP] != r->data_000_fd || idx->block_size != FIX_BLOCK_SIZE || r->pending_delete == UINT64_MAX)
        return false;
    struct msg_qv_t qv = {0};
    msg_kv_t kv = {.key = marker + DISK_RECORD_HEADER_SIZE,
                   .key_size = (uint32_t)record_header_load_le(marker + KEY_SIZE_RECORD_OFFSET, 4),
                   .cf_size = (uint32_t)record_header_load_le(marker + CF_SIZE_RECORD_OFFSET, 4),
                   .qv = &qv};
    kv.cf = kv.key + kv.key_size;
    msg_cli_t msg = {.msg_size = size, .type = MSG_PUT, .kv = &kv};
    r->has_digest_calc = false;

    if (!build_idx_vars_old(r, &msg, bs, th)) {
        if (r->stop || r->bad_data || r->is_freed || r->idx_resizer != RESIZE_IDX_DONE)
            return false;
        r->has_digest_calc = false;

        if (!build_idx_vars_old(r, &msg, bs, th))
            return false;
    }
    uint8_t b = idx->idx_r_help->b;
    bool collision = idx->idx[b][idx->idx_r_help->k_idx].o_index != 0;

    if (collision && idx->coll_count_curr[b] == idx->coll_count_tot[b] && !resize_coll_keeper(r, b, bs, th->cid))
        return false;
    int32_t keeper = -1;

    if (r->idx_resizer >= RESIZE_IDX_PREPARED)
        keeper = add_key_to_keeper(r, b, &msg, 0, bs, th);
    uint32_t block = store_record(r, &msg, marker, th, collision ? idx->coll_count_curr[b] * COLL_KEEPER_SIZE : UINT32_MAX, 0, bs);

    if (block == 0 || block >= O_IDX_MAX_SIZE)
        return false;
    add_key_to_idx(r, marker, bs, block, 0, &msg, th);

    if (keeper >= 0)
        memcpy(idx->key_keeper[b] + keeper + DIGEST_SIZE_FULL, &block, OFFSET_COLL_KEEPER_SIZE);
    r->pending_delete++;
    r->has_digest_calc = false;
    return true;
}

static uint32_t gp_read_block(region_info_t *r_info, uint32_t read_block, uint8_t bs, uint8_t b, uint32_t block_size, uint64_t rw_off, uint32_t cli_rec_size,
                              uint16_t *out_bsize_factor, uint16_t *out_records_count, uint32_t *out_filled_zip_size, table_handler_t *t_handler, char *dt) {
    uint16_t bsize_factor = *out_bsize_factor;
    uint16_t records_count = *out_records_count;
    uint32_t r_filled_zip_size = *out_filled_zip_size;
    memset(r_info->rbuff, 0, block_size);
    uint32_t data_size;

    if (r_info->enable_block_compression == BLOCK_COMPRESSION_NONE) {
        data_size = read_file(r_info->r_idx_b[bs]->fd[b], r_info->rbuff, rw_off, block_size, r_info, t_handler->cid);
    } else {
        data_size = read_file(r_info->r_idx_b[bs]->fd[b], r_info->rbuff, rw_off, BLOCK_MAX_SIZE, r_info, t_handler->cid);

        if (data_size > 0) {
            const uint32_t input_size = data_size;

            if (input_size >= sizeof(data_size))
                memcpy(&data_size, r_info->rbuff, sizeof(data_size));

            if (data_size > 0) {
                uint64_t decompressed_size = 0;
                int decompress_result = decompress_block(r_info->rbuff, input_size, read_block, bs, r_info, &decompressed_size, 0, t_handler);

                if (decompress_result == 0) {
                    data_size = align_up(data_size, MAX_BSIZE_FACTOR);
                    memcpy(&records_count, r_info->rbuff + sizeof(uint32_t) + sizeof(uint64_t) - sizeof(uint16_t), sizeof(uint16_t));

                    if (r_info->rbuff_size < decompressed_size + cli_rec_size + MAX_BSIZE_FACTOR) {
                        uint8_t *rbuff_tmp = realloc(r_info->rbuff, decompressed_size + cli_rec_size + MAX_BSIZE_FACTOR);

                        if (rbuff_tmp == NULL) {
                            // TODO
                            fprintf(stderr, "%s WARN [RS_IDX=%015lu] Failed realloc rbuff to %lu\n", curr_dt(dt), t_handler->cid,
                                    decompressed_size + cli_rec_size + MAX_BSIZE_FACTOR);
                            graceful_exit(-1);
                        }
                        r_info->rbuff = rbuff_tmp;
                        r_info->rbuff_size = decompressed_size + cli_rec_size + MAX_BSIZE_FACTOR;
                    }
                    memcpy(r_info->rbuff, r_info->bbuff, decompressed_size);

                    if (r_info->zbuff_size < decompressed_size + MAX_BSIZE_FACTOR) {
                        uint8_t *zbuff_tmp = realloc(r_info->zbuff, decompressed_size + MAX_BSIZE_FACTOR);

                        if (zbuff_tmp == NULL) {
                            // TODO
                            fprintf(stderr, "%s WARN [RS_IDX=%015lu] Failed realloc rbuff to %lu\n", curr_dt(dt), t_handler->cid,
                                    decompressed_size + cli_rec_size + MAX_BSIZE_FACTOR);
                            graceful_exit(-1);
                        }
                        r_info->zbuff = zbuff_tmp;
                        r_info->zbuff_size = decompressed_size + MAX_BSIZE_FACTOR;
                    }
                    memcpy(r_info->zbuff, r_info->bbuff, decompressed_size);
                    bsize_factor = FIX_BSIZE_FACTOR;
                    r_filled_zip_size = ((decompressed_size + bsize_factor - 1) / bsize_factor);

                    if (log_level > 2)
                        fprintf(stderr, "%s DEBUG [RS_IDX=%015lu] Decompressed block=%u %s, r_filled_zip_size=%u, decompressed_size=%lu, data_size=%u, z_index=%u\n",
                                curr_dt(dt), t_handler->cid, read_block, r_info->uuid, r_filled_zip_size, decompressed_size, data_size,
                                r_info->r_idx_b[bs]->idx[b][read_block].z_index);
                } else {
                    // TODO data_fix
                    fprintf(stderr, "%s WARN [RS_IDX=%015lu] Failed decompress_snappy result=%u\n", curr_dt(dt), t_handler->cid, decompress_result);
                    graceful_exit(-1);
                }
            }
        } else {
            // TODO data_fix?
        }
    }
    *out_bsize_factor = bsize_factor;
    *out_records_count = records_count;
    *out_filled_zip_size = r_filled_zip_size;
    return data_size;
}

