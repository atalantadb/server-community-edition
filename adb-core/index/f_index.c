int write_qfl_dict(struct region_info_t *r_info, table_handler_t *t_handler) {
    char dt[DT_LOG_SIZE];
    r_info->qfl_dic_lens++;
    r_info->qfl_dic_total_size = 0;
    uint16_t s2b;
    uint8_t dict_buff[BLOCK_MAX_SIZE];
    memset(dict_buff, 0, BLOCK_MAX_SIZE);
    uint32_t buff_offset = 0;
    uint32_t meta_crc32;

    for (int i = 0; i < r_info->qfl_dic_lens; i++) {
        s2b = r_info->qfl_dic_size[i];

        if (r_info->qfl_dic_total_size + SHORT_SIZE + s2b >= BLOCK_MAX_SIZE - USED_META - sizeof(meta_crc32)) {
            fprintf(stderr, "%s ERROR [REGION_HANDLER=%015lu] Too much size of qualifier dictionary %s current %d\n", curr_dt(dt), t_handler->cid, r_info->uuid,
                    r_info->qfl_dic_total_size);
            return -10;
        }
        memcpy(dict_buff + USED_META + buff_offset, &s2b, SHORT_SIZE);
        buff_offset += SHORT_SIZE;
        r_info->qfl_dic_total_size += SHORT_SIZE;
        memcpy(dict_buff + USED_META + buff_offset, r_info->qfl_dic[i], s2b);
        buff_offset += s2b;
        r_info->qfl_dic_total_size += s2b;
    }
    fprintf(stderr, "%s DEBUG [REGION_HANDLER=%015lu] Dict %s, qfl_dic_lens=%d, qfl_dic_total_size=%d\n", curr_dt(dt), t_handler->cid, r_info->uuid, r_info->qfl_dic_lens,
            r_info->qfl_dic_total_size);
    read_file(r_info->r_idx_b[BLOCK_ARRAY_FIRST_POS]->fd[FBP], dict_buff, META_OFFSET, USED_META, r_info, t_handler->cid);
    meta_crc32 = crc_32(dict_buff, BLOCK_MAX_SIZE - sizeof(uint32_t));
    memcpy(dict_buff + BLOCK_MAX_SIZE - sizeof(uint32_t), &meta_crc32, sizeof(uint32_t));
#if !ENTERPRISE
    bool record_changed = t_handler->record_mutation != NULL && t_handler->record_mutation->changed;
#endif
    replicas_writer(r_info, dict_buff, FBP, META_OFFSET, BLOCK_MAX_SIZE, false, BLOCK_ARRAY_FIRST_POS, true, t_handler);
#if !ENTERPRISE
    if (t_handler->record_mutation != NULL && !r_info->stop && !r_info->bad_data && r_info->replica->replica_control == 0)
        t_handler->record_mutation->changed = record_changed;
#endif
    return 0;
}

void pack_qfl(region_info_t *r_info, uint8_t *buff, msg_cli_t *msg_cli, uint32_t *src_qfl_offset, uint32_t *dst_qfl_offset, uint16_t s2b, uint32_t qfl_to_del) {
    *src_qfl_offset -= QV_QFL_RECORD_OFFSET;
    memcpy(r_info->bbuff + *dst_qfl_offset, buff + *src_qfl_offset, TS_SIZE);
    *src_qfl_offset += TS_SIZE;
    *dst_qfl_offset += TS_SIZE;
    uint32_t i2b = (DICT_SIZE + qfl_to_del);
    memcpy(r_info->bbuff + *dst_qfl_offset, &i2b, INT_SIZE);
    *src_qfl_offset += QFL_SIZE_SIZE;
    *dst_qfl_offset += QFL_SIZE_SIZE;
    memcpy(&i2b, buff + *src_qfl_offset, INT_SIZE);
    memcpy(r_info->bbuff + *dst_qfl_offset, &i2b, INT_SIZE);
    *src_qfl_offset += VAL_SIZE_SIZE;
    *dst_qfl_offset += VAL_SIZE_SIZE;
    memcpy(r_info->bbuff + *dst_qfl_offset, &s2b, DICT_SIZE);
    *src_qfl_offset += msg_cli->kv->qv->qfl_size;
    *dst_qfl_offset += DICT_SIZE;
    memcpy(r_info->bbuff + *dst_qfl_offset, buff + *src_qfl_offset, i2b);
    *src_qfl_offset += i2b;
    *dst_qfl_offset += i2b;
}

int pack_qfls(region_info_t *r, uint8_t *buf, msg_cli_t *msg, bool del_qfl, table_handler_t *h) {
    if (log_level > 4) {
        char dt[DT_LOG_SIZE];
        fprintf(stderr, "%s TRACE [RS_IDX=%015lu] Ready dict pack %d\n", curr_dt(dt), h->cid, buf[ZIP_INFO_RECORD_OFFSET]);
    }

    if (msg->msg_size + MAX_BSIZE_FACTOR >= REAL_MAX_MSG_SIZE || (buf[ZIP_INFO_RECORD_OFFSET] & 0x01) == 1 || (buf[ZIP_INFO_RECORD_OFFSET] & 0x02) != 0x02)
        return 0;
    bool first = true;
    uint32_t word;
    uint32_t src = KEY_SIZE_RECORD_OFFSET + KEY_RECORD_OFFSET + msg->kv->key_size + msg->kv->cf_size;
    uint32_t dst = src;
    memcpy(r->bbuff, buf, dst);
    uint32_t total = msg->msg_size;
    memcpy(&msg->kv->qv_size, buf + QV_SIZE_RECORD_OFFSET, sizeof(msg->kv->qv_size));
    uint32_t new_qv = msg->kv->qv_size;

    if (r->log_level > 3) {
        if (!r->qfl_info) {
            r->qfl_info = malloc(QFL_INFO_CAP);

            if (!r->qfl_info) {
                char dt[DT_LOG_SIZE];
                fprintf(stderr, "%s ERROR [RS_IDX=%015lu] Failed malloc qfl_info=%u bytes in pack_qfls\n", curr_dt(dt), h->cid, QFL_INFO_CAP);
                return -1;
            }
        }
        r->qfl_info[0] = '\0';
    }

    do {
        if (src > total || total - src < QV_QFL_RECORD_OFFSET) {
            char dt[DT_LOG_SIZE];
            fprintf(stderr, "%s WARN [RS_IDX=%015lu] Corrupted qfl/val sizes, msg_size=%u\n", curr_dt(dt), h->cid, total);
            return -1;
        }
        uint32_t deleted = 0;
        memcpy(&word, buf + src + TS_SIZE, INT_SIZE);
        uint32_t val_len;
        uint32_t qfl_len = word > 0x80000000U ? word - 0x80000000U : word;
        memcpy(&val_len, buf + src + TS_SIZE + QFL_SIZE_SIZE, VAL_SIZE_SIZE);
        uint32_t left = total - src - QV_QFL_RECORD_OFFSET;

        if (qfl_len > left || val_len > left - qfl_len)
            return -1;

        if (word > 0x80000000) {
            if (del_qfl) {
                msg->kv->qv->qfl_size = word - 0x80000000;
                uint32_t special_rec_size = TS_SIZE + QFL_SIZE_SIZE + VAL_SIZE_SIZE + msg->kv->qv->qfl_size + 0;
                src += special_rec_size;
                new_qv -= special_rec_size;
                continue;
            } else {
                deleted = 0x80000000;
                word -= 0x80000000;
            }
        }
        msg->kv->qv->qfl_size = word;
        memcpy(&word, buf + src + TS_SIZE + QFL_SIZE_SIZE, INT_SIZE);
        msg->kv->qv->val_size = word;
        bool found = false;
        new_qv -= (msg->kv->qv->qfl_size - DICT_SIZE);
        src += QV_QFL_RECORD_OFFSET;

        if (r->log_level > 3) {
            char tmp[QFL_INFO_CAP / 2];
            char name_buf[QFL_INFO_CAP / 4];
            uint32_t qfl_len = msg->kv->qv->qfl_size;
            uint32_t copy_len = (qfl_len < sizeof(name_buf) - 1) ? qfl_len : (sizeof(name_buf) - 1);
            memcpy(name_buf, buf + src, copy_len);
            name_buf[copy_len] = '\0';
            snprintf(tmp, sizeof(tmp), "%s%s:%u", first ? "" : ", ", name_buf, msg->kv->qv->val_size);
            size_t cur_len = strlen(r->qfl_info);
            size_t add_len = strlen(tmp);

            if (cur_len + add_len + 1 < QFL_INFO_CAP) {
                strcat(r->qfl_info, tmp);
                first = false;
            }
        }

        for (uint16_t i = 0; i < r->qfl_dic_lens; i++) {
            if (msg->kv->qv->qfl_size == r->qfl_dic_size[i]) {
                if (memcmp(r->qfl_dic[i], buf + src, r->qfl_dic_size[i]) == 0) {
                    found = true;
                    pack_qfl(r, buf, msg, &src, &dst, i, deleted);
                    break;
                }
            }
        }

        if (!found) {
            char *entry = malloc(msg->kv->qv->qfl_size);

            if (!entry) {
                char dt[DT_LOG_SIZE];
                fprintf(stderr, "%s ERROR [RS_IDX=%015lu] Failed malloc qfl_dic=%u bytes\n", curr_dt(dt), h->cid, msg->kv->qv->qfl_size);
                return -1;
            }
            r->qfl_dic[r->qfl_dic_lens] = entry;
            r->qfl_dic_size[r->qfl_dic_lens] = msg->kv->qv->qfl_size;

            if (msg->kv->qv->qfl_size > r->max_dict_qfl_len)
                r->max_dict_qfl_len = msg->kv->qv->qfl_size;
            memcpy(r->qfl_dic[r->qfl_dic_lens], buf + src, msg->kv->qv->qfl_size);
            pack_qfl(r, buf, msg, &src, &dst, r->qfl_dic_lens, deleted);
            int rc = write_qfl_dict(r, h);

            if (rc != 0) {
                char dt[DT_LOG_SIZE];
                fprintf(stderr, "%s ERROR [RS_IDX=%015lu] Cannot write dict=%s, result_write_dict=%d\n", curr_dt(dt), h->cid, r->r_fname, rc);
                return -1;
            }
        }
    } while (total != src);
    uint32_t qsize = total - (msg->kv->qv_size - new_qv);

    if (total - (msg->kv->qv_size - new_qv) + MAX_BSIZE_FACTOR >= REAL_MAX_MSG_SIZE)
        return 0;
    memcpy(buf, r->bbuff, qsize);
    buf[ZIP_INFO_RECORD_OFFSET] &= ~0x02;

    if (log_level > 4) {
        char dt[DT_LOG_SIZE];
        fprintf(stderr, "%s TRACE [RS_IDX=%015lu] Dict set %d\n", curr_dt(dt), h->cid, buf[ZIP_INFO_RECORD_OFFSET]);
    }

    if (r->log_level > 3) {
        char dt[DT_LOG_SIZE];
        fprintf(stderr, "%s TRACE [RS_IDX=%015lu] Pack QFL values: %s\n", curr_dt(dt), h->cid, r->qfl_info[0] ? r->qfl_info : "(empty)");
    }
    word = new_qv;
    memcpy(buf + QV_SIZE_RECORD_OFFSET, &word, INT_SIZE);
    msg->msg_size = word = total - (msg->kv->qv_size - new_qv);
    memcpy(buf, &word, INT_SIZE);
    msg->kv->qv_size = new_qv;
    msg->kv->qv->qfl_size = 2;
    r->msg_cli_dict_done = true;
    return 0;
}


int calc_extract_qfls_size(region_info_t *r_info, char *src_buff, uint32_t msg_size, uint32_t key_size, uint32_t cf_size, uint32_t qv_size, uint32_t dst_capacity,
                           uint32_t *required_size, uint8_t bs, uint64_t cid) {
    uint64_t qv_offset = KEY_SIZE_RECORD_OFFSET + KEY_RECORD_OFFSET;
    qv_offset += key_size;
    qv_offset += cf_size;

    if (r_info == NULL || required_size == NULL || src_buff == NULL || qv_offset > msg_size || qv_size != msg_size - qv_offset) {
        return -1;
    }

    if ((src_buff[ZIP_INFO_RECORD_OFFSET] & 0x02) != 0) {
        *required_size = msg_size;
        return 0;
    }
    uint64_t max_field_count = qv_size / (QV_QFL_RECORD_OFFSET + DICT_SIZE);
    uint64_t max_qfl_growth = r_info->max_dict_qfl_len > DICT_SIZE ? r_info->max_dict_qfl_len - DICT_SIZE : 0;
    uint64_t max_extract_size = msg_size + max_field_count * max_qfl_growth;

    if (max_extract_size <= dst_capacity && max_extract_size <= RECORD_SIZE_LIMIT) {
        *required_size = (uint32_t)max_extract_size;
        return 0;
    }
    uint64_t src_offset = qv_offset;
    uint64_t result_size = qv_offset;

    while (src_offset < msg_size) {
        if (QV_QFL_RECORD_OFFSET + DICT_SIZE > msg_size - src_offset)
            return -1;
        uint32_t val_size;
        uint32_t qfl_size;
        uint16_t dict_pos;
        memcpy(&qfl_size, src_buff + src_offset + TS_SIZE, QFL_SIZE_SIZE);
        memcpy(&val_size, src_buff + src_offset + TS_SIZE + QFL_SIZE_SIZE, VAL_SIZE_SIZE);
        memcpy(&dict_pos, src_buff + src_offset + QV_QFL_RECORD_OFFSET, DICT_SIZE);

        if ((qfl_size & ~0x80000000u) != DICT_SIZE)
            return -1;

        if (dict_pos >= r_info->qfl_dic_lens) {
            char dt[DT_LOG_SIZE];
            fprintf(stderr, "%s WARN [RS_IDX=%015lu] Dict len %s (bs=%d) is incorrect s2b=%u >= qfl_dic_lens=%d\n", curr_dt(dt), cid, r_info->uuid, bs, dict_pos,
                    r_info->qfl_dic_lens);
            return -1;
        }

        if (val_size > msg_size - src_offset - QV_QFL_RECORD_OFFSET - DICT_SIZE)
            return -1;
        result_size += QV_QFL_RECORD_OFFSET + r_info->qfl_dic_size[dict_pos] + val_size;

        if (result_size > RECORD_SIZE_LIMIT || result_size > UINT32_MAX)
            return -1;
        src_offset += QV_QFL_RECORD_OFFSET + DICT_SIZE + val_size;
    }

    if (src_offset != msg_size)
        return -1;
    *required_size = (uint32_t)result_size;
    return 0;
}


static int prepare_extract_resp_buff(region_info_t *r_info, char *src_buff, uint32_t msg_size, uint32_t key_size, uint32_t cf_size, uint32_t qv_size, uint8_t bs,
                                     msg_srv_t *msg_srv, uint64_t cid) {
    if (msg_srv == NULL)
        return -1;
    uint32_t required_size;

    if (calc_extract_qfls_size(r_info, src_buff, msg_size, key_size, cf_size, qv_size, msg_srv->curr_max_msg_size, &required_size, bs, cid) != 0)
        return -1;

    if (required_size > msg_srv->curr_max_msg_size)
        return realloc_resp_buff(msg_srv, required_size, cid);
    return 0;
}

int prepare_extract_region_buff(region_info_t *r_info, char *src_buff, uint32_t msg_size, uint32_t key_size, uint32_t cf_size, uint32_t qv_size, uint8_t bs,
                                uint8_t **dst_buff, uint64_t *dst_capacity, uint64_t cid) {
    if (dst_buff == NULL || dst_capacity == NULL)
        return -1;
    uint32_t capacity = *dst_capacity > UINT32_MAX ? UINT32_MAX : (uint32_t)*dst_capacity;
    uint32_t required_size;

    if (calc_extract_qfls_size(r_info, src_buff, msg_size, key_size, cf_size, qv_size, capacity, &required_size, bs, cid) != 0)
        return -1;

    if (required_size <= *dst_capacity)
        return 0;
    uint8_t *dst_buff_tmp = realloc(*dst_buff, required_size);

    if (dst_buff_tmp == NULL)
        return -1;
    *dst_buff = dst_buff_tmp;
    *dst_capacity = required_size;
    return 0;
}

uint32_t extract_qfls(region_info_t *r_info, char *src_buff, char *dst_buff, uint32_t dst_capacity, uint32_t msg_size, uint32_t key_size, uint32_t cf_size, uint32_t qv_size,
                      uint8_t bs, bool force, uint64_t cid) {
    (void)force;

    if (log_level > 4) {
        char dt[DT_LOG_SIZE];
        fprintf(stderr, "%s TRACE [RS_IDX=%015lu] Ready dict extract %d\n", curr_dt(dt), cid, src_buff[ZIP_INFO_RECORD_OFFSET]);
    }
    uint32_t required_size;

    if (dst_buff == NULL || calc_extract_qfls_size(r_info, src_buff, msg_size, key_size, cf_size, qv_size, dst_capacity, &required_size, bs, cid) != 0 ||
        required_size > dst_capacity) {
        return 0;
    }

    if ((src_buff[ZIP_INFO_RECORD_OFFSET] & 0x02) != 0) {
        memcpy(dst_buff, src_buff, msg_size);
        return msg_size;
    }
    uint32_t new_qv_size = 0;
    uint32_t src_qfl_offset = KEY_SIZE_RECORD_OFFSET + KEY_RECORD_OFFSET + key_size + cf_size;
    uint32_t dst_qfl_offset = src_qfl_offset;
    memcpy(dst_buff, src_buff, dst_qfl_offset);
    uint32_t msg_size_count = msg_size;
    uint16_t s2b;
    uint32_t i2b;
    bool first_qfl = true;

    if (r_info->log_level > 3) {
        if (r_info->qfl_info == NULL) {
            r_info->qfl_info = malloc(QFL_INFO_CAP);

            if (r_info->qfl_info == NULL) {
                char dt[DT_LOG_SIZE];
                fprintf(stderr, "%s ERROR [RS_IDX=%015lu] Failed malloc qfl_info=%u bytes in extract_qfls\n", curr_dt(dt), cid, QFL_INFO_CAP);
                return 0;
            }
        }
        r_info->qfl_info[0] = '\0';
    }
    while (src_qfl_offset < msg_size_count) {
        if (QV_QFL_RECORD_OFFSET + DICT_SIZE > msg_size_count - src_qfl_offset)
            return 0;

        if (dst_qfl_offset > dst_capacity || QV_QFL_RECORD_OFFSET > dst_capacity - dst_qfl_offset)
            return 0;
        memcpy(dst_buff + dst_qfl_offset, src_buff + src_qfl_offset, TS_SIZE);
        uint32_t encoded_qfl_size;
        memcpy(&encoded_qfl_size, src_buff + src_qfl_offset + TS_SIZE, QFL_SIZE_SIZE);

        if ((encoded_qfl_size & ~0x80000000u) != DICT_SIZE)
            return 0;
        src_qfl_offset += QV_QFL_RECORD_OFFSET;
        memcpy(&s2b, src_buff + src_qfl_offset, DICT_SIZE);

        if (s2b >= r_info->qfl_dic_lens) {
            char dt[DT_LOG_SIZE];
            fprintf(stderr, "%s WARN [RS_IDX=%015lu] Dict len %s (bs=%d) is incorrect s2b=%d >= qfl_dic_lens=%d, dst_qfl_offset=%d\n", curr_dt(dt), cid, r_info->uuid, bs, s2b,
                    r_info->qfl_dic_lens, dst_qfl_offset);
            return 0;
        }
        i2b = r_info->qfl_dic_size[s2b];
        dst_qfl_offset += TS_SIZE;
        uint32_t decoded_qfl_size = i2b | (encoded_qfl_size & 0x80000000u);
        memcpy(dst_buff + dst_qfl_offset, &decoded_qfl_size, INT_SIZE);
        dst_qfl_offset += QFL_SIZE_SIZE;
        src_qfl_offset -= QFL_SIZE_SIZE;
        memcpy(&i2b, src_buff + src_qfl_offset, INT_SIZE);

        if (i2b > msg_size_count - src_qfl_offset - QFL_SIZE_SIZE - DICT_SIZE || VAL_SIZE_SIZE > dst_capacity - dst_qfl_offset ||
            r_info->qfl_dic_size[s2b] > dst_capacity - dst_qfl_offset - VAL_SIZE_SIZE || i2b > dst_capacity - dst_qfl_offset - VAL_SIZE_SIZE - r_info->qfl_dic_size[s2b])
            return 0;
        new_qv_size += QV_QFL_RECORD_OFFSET + r_info->qfl_dic_size[s2b] + i2b;
        memcpy(dst_buff + dst_qfl_offset, &i2b, INT_SIZE);
        dst_qfl_offset += VAL_SIZE_SIZE;
        memcpy(dst_buff + dst_qfl_offset, r_info->qfl_dic[s2b], r_info->qfl_dic_size[s2b]);
        dst_qfl_offset += r_info->qfl_dic_size[s2b];
        src_qfl_offset += QFL_SIZE_SIZE + DICT_SIZE;

        if (r_info->log_level > 3) {
            char name_buf[QFL_INFO_CAP / 4];
            uint32_t qfl_len = r_info->qfl_dic_size[s2b];
            uint32_t copy_len = (qfl_len < sizeof(name_buf) - 1) ? qfl_len : (sizeof(name_buf) - 1);
            memcpy(name_buf, r_info->qfl_dic[s2b], copy_len);
            name_buf[copy_len] = '\0';
            char tmp[QFL_INFO_CAP / 2];
            snprintf(tmp, sizeof(tmp), "%s%s:%u", first_qfl ? "" : ", ", name_buf, i2b);
            size_t cur_len = strlen(r_info->qfl_info);
            size_t add_len = strlen(tmp);

            if (cur_len + add_len + 1 < QFL_INFO_CAP) {
                strcat(r_info->qfl_info, tmp);
                first_qfl = false;
            }
        }
        memcpy(dst_buff + dst_qfl_offset, src_buff + src_qfl_offset, i2b);
        src_qfl_offset += i2b;
        dst_qfl_offset += i2b;
    }

    if (src_qfl_offset != msg_size_count)
        return 0;
    msg_size = dst_qfl_offset;
    memcpy(dst_buff + 0, &msg_size, INT_SIZE);
    memcpy(dst_buff + QV_SIZE_RECORD_OFFSET, &new_qv_size, INT_SIZE);
    dst_buff[ZIP_INFO_RECORD_OFFSET] |= 0x02;

    if (log_level > 4) {
        char dt[DT_LOG_SIZE];
        fprintf(stderr, "%s TRACE [RS_IDX=%015lu] Dict unset %d\n", curr_dt(dt), cid, dst_buff[ZIP_INFO_RECORD_OFFSET]);
    }

    if (r_info->log_level > 3) {
        char dt[DT_LOG_SIZE];
        fprintf(stderr, "%s TRACE [RS_IDX=%015lu] Extract QFL list: %s\n", curr_dt(dt), cid, r_info->qfl_info[0] ? r_info->qfl_info : "(empty)");
    }
    return msg_size;
}

void del_from_index(struct region_info_t *r_info, uint32_t read_block, msg_cli_t *msg_cli, table_handler_t *t_handler, uint32_t coll_pos, uint8_t bs) {
    uint8_t b = r_info->r_idx_b[bs]->idx_r_help->b;

    if (coll_pos == -1) {
        union i2b_u i2b;
        uint8_t digest[DIGEST_SIZE_FULL];
        calc_hash(msg_cli->kv->key, msg_cli->kv->key_size, digest);
        calc_hash_full(msg_cli->kv->key, msg_cli->kv->key_size, digest, DIGEST_SIZE_SMALL);
        uint32_t k_idx = r_info->r_idx_b[bs]->idx_r_help->k_idx;

        for (uint32_t c = 0; c < r_info->r_idx_b[bs]->coll_count_curr[b] * ((uint32_t)COLL_KEEPER_SIZE); c += ((uint32_t)COLL_KEEPER_SIZE)) {
            if (memcmp(digest, r_info->r_idx_b[bs]->coll_keeper[b] + c, ((uint32_t)DIGEST_SIZE_FULL)) == 0) {
                memcpy(i2b.byte, r_info->r_idx_b[bs]->coll_keeper[b] + c + ((uint32_t)DIGEST_SIZE_FULL), ((uint32_t)OFFSET_COLL_KEEPER_SIZE));
                i2b.byte[OFFSET_COLL_KEEPER_SIZE] = 0;

                if (i2b.integer_val == read_block) {
                    coll_pos = c;
                    remove_coll(r_info, b, coll_pos, bs);
                    break;
                } else {
                    char dt[DT_LOG_SIZE];
                    fprintf(stderr, "%s WARN [RS_IDX=%015lu] Delete coll not found %s, k_idx=%d, c_idx=%d, o_idx=%d, b_offset=%d, read_block=%d\n", curr_dt(dt),
                            t_handler->cid, r_info->r_idx_b[bs]->fname, k_idx, r_info->r_idx_b[bs]->idx_r_help->c_idx, r_info->r_idx_b[bs]->idx[b][k_idx].o_index,
                            i2b.integer_val, read_block);
                }
            }
        }

        if (coll_pos == -1) {
            uint32_t c_idx_bkp = r_info->r_idx_b[bs]->idx[b][k_idx].c_index;
            r_info->r_idx_b[bs]->moved_coll = false;
            del_in_chain(r_info, k_idx, 0, bs, t_handler);
            bool remove_from_coll = false;
            uint32_t coll_pos = 0;

            for (coll_pos = 0; coll_pos < r_info->r_idx_b[bs]->coll_count_curr[b] * ((uint32_t)COLL_KEEPER_SIZE); coll_pos += ((uint32_t)COLL_KEEPER_SIZE)) {
                uint32_t k_idx_pos = DIGEST_SIZE_FULL + OFFSET_COLL_KEEPER_SIZE;
                memcpy(i2b.byte, r_info->r_idx_b[bs]->coll_keeper[b] + coll_pos + k_idx_pos, (uint8_t)COLL_IDX_SIZE);

                if (k_idx == i2b.integer_val) {
                    uint8_t c_idx_len = 3;
#ifdef COLL_LOB_TEST
                    c_idx_len = 1;
#endif
                    if (memcmp(&c_idx_bkp, r_info->r_idx_b[bs]->coll_keeper[b] + coll_pos + C_IDX_POS, c_idx_len) == 0) {
                        i2b.byte[K0_POS] = r_info->r_idx_b[bs]->coll_keeper[b][coll_pos + K0_POS];
                        i2b.byte[K1_POS] = r_info->r_idx_b[bs]->coll_keeper[b][coll_pos + K1_POS];
                        i2b.byte[K2_POS] = r_info->r_idx_b[bs]->coll_keeper[b][coll_pos + K2_POS];
                        i2b.byte[K3_POS] = r_info->r_idx_b[bs]->coll_keeper[b][coll_pos + K3_POS];
                        i2b.integer_val = i2b.integer_val & r_info->r_idx_b[bs]->idx_mask[b];
                        r_info->r_idx_b[bs]->idx_r_help->k_idx = i2b.integer_val;
#ifdef COLL_LOB_TEST
                        r_info->r_idx_b[bs]->idx_r_help->c_idx = r_info->r_idx_b[bs]->coll_keeper[b][coll_pos + C_IDX_POS];
#else
                        r_info->r_idx_b[bs]->idx_r_help->c_idx = r_info->r_idx_b[bs]->coll_keeper[b][coll_pos + C_IDX_POS] +
                                                                 (r_info->r_idx_b[bs]->coll_keeper[b][coll_pos + C_IDX_POS + 1] << 8) +
                                                                 ((r_info->r_idx_b[bs]->coll_keeper[b][coll_pos + C_IDX_POS + 2] & 0x7Fu) << 16);
#endif
                        // TODO ЗАПРЕТИТЬ УДАЛЕНИЯ ВО ВРЕМЯ РЕСАЙЗА
                        if (find_k_idx(r_info, true, 0, bs, t_handler) == false) {
                            char dt[DT_LOG_SIZE];
                            fprintf(stderr, "%s ERROR [RS_IDX=%015lu] Cannot put collision into index %s[%d]. TODO resize it.\n", curr_dt(dt), t_handler->cid,
                                    r_info->r_idx_b[bs]->fname, b);
                            finish_thread(r_info, 38, true, t_handler);
                            ;
                        }
                        k_idx = r_info->r_idx_b[bs]->idx_r_help->k_idx;

                        if (r_info->r_idx_b[bs]->idx[b][k_idx].o_index == 0) {
                            if (r_info->r_idx_b[bs]->f_idx_size[b] < pow(2, 16))
                                r_info->r_idx_b[bs]->k1_index[b][k_idx] = r_info->r_idx_b[bs]->coll_keeper[b][coll_pos + K1_POS];

                            if (r_info->r_idx_b[bs]->f_idx_size[b] < pow(2, 24))
                                r_info->r_idx_b[bs]->k2_index[b][k_idx] = r_info->r_idx_b[bs]->coll_keeper[b][coll_pos + K2_POS];
                            r_info->r_idx_b[bs]->idx[b][k_idx].k3_index = r_info->r_idx_b[bs]->coll_keeper[b][coll_pos + K3_POS];
                            memcpy(i2b.byte, r_info->r_idx_b[bs]->coll_keeper[b] + coll_pos + ((uint32_t)DIGEST_SIZE_FULL), ((uint32_t)OFFSET_COLL_KEEPER_SIZE));
                            i2b.byte[OFFSET_COLL_KEEPER_SIZE] = 0;
                            r_info->r_idx_b[bs]->idx[b][k_idx].o_index = i2b.integer_val;
                            remove_coll(r_info, b, coll_pos, bs);
                            break;
                        }
                    }
                }
            }
        }
    } else {
        remove_coll(r_info, b, coll_pos, bs);
    }
    r_info->r_idx_b[bs]->f_idx_curr_size[b]--;
}


static int ensure_resp_tail_capacity(msg_srv_t *msg_srv, size_t need) {
    const size_t MIN_CAP = 1024;
    uint8_t *base = (uint8_t *)msg_srv->resp_buff_base;
    uint8_t *dst = (uint8_t *)msg_srv->resp_buff;

    if (!base) {
        base = dst;
        msg_srv->resp_buff_base = (char *)base;
    }

    if (!base || !dst) {
        return -1;
    }

    if (dst < base) {
        return -1;
    }
    size_t offset = (size_t)(dst - base);
    size_t total = (size_t)msg_srv->total_max_msg_size;

    if (total < offset + (size_t)msg_srv->curr_max_msg_size) {
        total = offset + (size_t)msg_srv->curr_max_msg_size;
    }

    if (need > SIZE_MAX - offset) {
        return -1;
    }
    size_t required = offset + need;

    if (total >= required) {
        msg_srv->total_max_msg_size = (uint32_t)total;
        msg_srv->curr_max_msg_size = (uint32_t)(total - offset);
        return 0;
    }
    size_t new_total = total ? total : MIN_CAP;

    if (new_total < MIN_CAP) {
        new_total = MIN_CAP;
    }
    while (new_total < required) {
        if (new_total > SIZE_MAX / 2) {
            new_total = required;
            break;
        }
        new_total *= 2;
    }

    if (new_total > UINT32_MAX) {
        return -1;
    }
    uint8_t *new_base = (uint8_t *)realloc(base, new_total);

    if (!new_base) {
        return -1;
    }
    base = new_base;
    dst = base + offset;
    msg_srv->resp_buff_base = (char *)base;
    msg_srv->resp_buff = (char *)dst;
    msg_srv->total_max_msg_size = (uint32_t)new_total;
    msg_srv->curr_max_msg_size = (uint32_t)(new_total - offset);
    return 0;
}

static int16_t extract_get_put_key(region_info_t *r_info, msg_cli_t *request, msg_cli_t *record, const uint8_t *bytes, uint32_t *key_capacity, uint32_t *cf_capacity,
                                   table_handler_t *handler) {
    bool safe_read = request == handler->msg_cli && request->type == MSG_GET && atomic_load(&handler->is_client) && handler->mutation_req_count == 0 &&
                     request->lob_info != 2 &&
                     (handler->append_compaction_piggyback == NULL || (!handler->append_compaction_piggyback->active && !handler->append_compaction_piggyback->local_applied));
    int16_t result = get_put_key_from_msg_bytes_checked(record, bytes, key_capacity, cf_capacity, handler->cid);

    if (result == KEY_EXTRACT_NOMEM || result == KEY_EXTRACT_INVALID_STATE) {
        if (!safe_read) {
            stop_region_after_key_error(r_info, result, handler);
            return GET_PUT_EXTRACT_ERROR;
        }
        char dt[DT_LOG_SIZE];
        fprintf(stderr, "%s WARN [RS_IDX=%015lu] Cannot extract GET key, code=%d; closing request\n", curr_dt(dt), handler->cid, result);
        do_r_unlock(r_info, 121, true, handler);
        finish_thread(r_info, 10, false, handler);
    }
    return result;
}
