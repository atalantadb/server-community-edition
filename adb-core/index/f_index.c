uint32_t add_key_to_keeper(struct region_info_t *r_info, uint8_t b, msg_cli_t *msg_get, uint32_t b_offset, uint8_t bs, table_handler_t *t_handler) {
    uint8_t digest[DIGEST_SIZE_FULL];
    calc_hash(msg_get->kv->key, msg_get->kv->key_size, digest);
    calc_hash_full(msg_get->kv->key, msg_get->kv->key_size, digest, DIGEST_SIZE_SMALL);
    union i2b_u i2b;
    i2b.integer_val = b_offset;

    for (int c = 0; c < r_info->r_idx_b[bs]->key_count_curr[b] * ((uint32_t)COLL_KEEPER_SIZE); c += ((uint32_t)COLL_KEEPER_SIZE)) {
        if (digest[0] == r_info->r_idx_b[bs]->key_keeper[b][c] && digest[1] == r_info->r_idx_b[bs]->key_keeper[b][c + 1]) {
            if (memcmp(digest, r_info->r_idx_b[bs]->key_keeper[b] + c, ((uint32_t)DIGEST_SIZE_FULL)) == 0) {
                memcpy(r_info->r_idx_b[bs]->key_keeper[b] + c + ((uint32_t)DIGEST_SIZE_FULL), i2b.byte, ((uint32_t)OFFSET_COLL_KEEPER_SIZE));
                return c;
            }
        }
    }

    if (r_info->r_idx_b[bs]->key_count_curr[b] == r_info->r_idx_b[bs]->key_count_tot[b])
        if (!resize_key_keeper(r_info, b, bs, t_handler->cid)) {
            stop_region_after_key_error(r_info, KEY_EXTRACT_NOMEM, t_handler);
            finish_thread(r_info, 38, true, t_handler);
        }
    uint32_t kpos = r_info->r_idx_b[bs]->key_count_curr[b] * ((uint32_t)COLL_KEEPER_SIZE);
    memcpy(r_info->r_idx_b[bs]->key_keeper[b] + kpos, digest, ((uint32_t)DIGEST_SIZE_FULL));
    memcpy(r_info->r_idx_b[bs]->key_keeper[b] + kpos + ((uint32_t)DIGEST_SIZE_FULL), i2b.byte, ((uint32_t)OFFSET_COLL_KEEPER_SIZE));
    r_info->r_idx_b[bs]->key_count_curr[b]++;
    return kpos;
}


void oc_index_corrector(region_info_t *r_info, uint8_t b, msg_cli_t *msg_get, uint32_t b_offset, uint32_t k_idx, uint8_t bs, table_handler_t *t_handler) {
    uint8_t digest[DIGEST_SIZE_FULL];
    bool is_digest_calc = false;
    calc_hash(msg_get->kv->key, msg_get->kv->key_size, digest);

    for (int c = 0; c < r_info->r_idx_b[bs]->coll_count_curr[b] * ((uint32_t)COLL_KEEPER_SIZE); c += ((uint32_t)COLL_KEEPER_SIZE)) {
        if (digest[0] == r_info->r_idx_b[bs]->coll_keeper[b][c] && digest[1] == r_info->r_idx_b[bs]->coll_keeper[b][c + 1]) {
            if (!is_digest_calc) {
                calc_hash_full(msg_get->kv->key, msg_get->kv->key_size, digest, DIGEST_SIZE_SMALL);
                is_digest_calc = true;
            }

            if (memcmp(digest, r_info->r_idx_b[bs]->coll_keeper[b] + c, ((uint32_t)DIGEST_SIZE_FULL)) == 0) {
                union i2b_u i2b;
                i2b.integer_val = b_offset;
                memcpy(r_info->r_idx_b[bs]->coll_keeper[b] + c + ((uint32_t)DIGEST_SIZE_FULL), i2b.byte, ((uint32_t)OFFSET_COLL_KEEPER_SIZE));
                return;
            }
        }
    }

    if (k_idx == -1) {
        memcpy(r_info->digest, digest, DIGEST_SIZE_SMALL);
        r_info->has_digest_calc = true;
        build_hash_params(msg_get, r_info, bs);
        r_info->has_digest_calc = false;

        while (find_k_idx(r_info, true, 0, bs, t_handler) == false)
            sleep(1); // Если попали на ресайзинг, подождем. TODO Подумать, что если случится переезд региона
        k_idx = r_info->r_idx_b[bs]->idx_r_help->k_idx;
    }
    r_info->r_idx_b[bs]->idx[b][k_idx].o_index = b_offset;
    return;
}


inline static uint32_t add_qfl_to_record(region_info_t *r_info, msg_cli_t *msg_cli, uint8_t *buff, uint32_t qv_offset_prev, uint32_t qv_offset, uint32_t qv_size) {
    qv_size = qv_offset - qv_offset_prev;
    memcpy(buff + msg_cli->msg_size, r_info->zbuff + qv_offset_prev, qv_size);
    msg_cli->msg_size += qv_size;
    memcpy(buff, &msg_cli->msg_size, sizeof(msg_cli->msg_size));
    msg_cli->kv->qv_size += qv_size;
    memcpy(buff + QV_SIZE_RECORD_OFFSET, &msg_cli->kv->qv_size, sizeof(msg_cli->kv->qv_size));
    return msg_cli->msg_size;
}


inline static bool ensure_qfl_capacity(msg_cli_t *msg_any, uint32_t *allocated_qfl_size, uint32_t qfl_size) {
    if (*allocated_qfl_size >= qfl_size)
        return true;
    uint8_t *qfl_tmp = realloc(msg_any->kv->qv->qfl, qfl_size);

    if (qfl_tmp == NULL)
        return false;
    msg_any->kv->qv->qfl = qfl_tmp;
    *allocated_qfl_size = qfl_size;
    return true;
}

inline static void free_get_put_link(msg_cli_t *msg_get) {
    free(msg_get->kv->qv->qfl);
    free(msg_get->kv->cf);
    free(msg_get->kv->key);
    msg_get->kv->qv->qfl = NULL;
    msg_get->kv->cf = NULL;
    msg_get->kv->key = NULL;
}


inline static uint32_t iterate_by_qv(uint8_t *buff, msg_cli_t *msg_any, uint32_t *allocated_qfl_size, uint32_t qv_offset, uint32_t qv_end, bool allow_delete_qfl, uint64_t ts,
                                     uint32_t qfl, uint32_t val) {
    uint32_t qv_header_size = sizeof(msg_any->kv->qv->ts) + sizeof(msg_any->kv->qv->qfl_size) + sizeof(msg_any->kv->qv->val_size);

    if (qv_offset > qv_end || qv_header_size > qv_end - qv_offset)
        return 0;
    memcpy(&ts, buff + qv_offset, sizeof(ts));
    qv_offset += sizeof(msg_any->kv->qv->ts);
    memcpy(&qfl, buff + qv_offset, sizeof(qfl));
    qv_offset += sizeof(msg_any->kv->qv->qfl_size);
    memcpy(&val, buff + qv_offset, sizeof(val));
    qv_offset += sizeof(msg_any->kv->qv->val_size);
    bool delete_qfl = (qfl & 0x80000000U) != 0;

    if (delete_qfl && allow_delete_qfl == false)
        return 0;
    uint32_t qfl_size = qfl & ~0x80000000U;

    if (qfl_size > qv_end - qv_offset)
        return 0;

    if (val > qv_end - qv_offset - qfl_size)
        return 0;

    if (qfl_size > 0 && ensure_qfl_capacity(msg_any, allocated_qfl_size, qfl_size) == false)
        return 0;
    msg_any->kv->qv->ts = ts;
    msg_any->kv->qv->qfl_size = qfl;
    msg_any->kv->qv->val_size = val;

    if (qfl_size > 0)
        memcpy(msg_any->kv->qv->qfl, buff + qv_offset, qfl_size);
    qv_offset += qfl_size;
    qv_offset += val;
    return qv_offset;
}


uint16_t compress_msg(uint8_t *buff, msg_cli_t *msg_cli, struct region_info_t *r_info, uint32_t block_size, table_handler_t *t_handler) {
    uint32_t qv_offset = KEY_SIZE_RECORD_OFFSET + KEY_RECORD_OFFSET + msg_cli->kv->key_size + msg_cli->kv->cf_size;
    uint8_t *data_ptr = buff + qv_offset;
    uint32_t data_size = msg_cli->msg_size - qv_offset;
    int compressed_data_size = LZ4_compress_default(data_ptr, r_info->zbuff, data_size, r_info->zbuff_size);
    uint32_t rec_data_size;

    if (compressed_data_size <= 0 || (uint32_t)compressed_data_size >= data_size || (uint32_t)compressed_data_size >= block_size) {
        rec_data_size = data_size;
    } else {
        memcpy(data_ptr, r_info->zbuff, compressed_data_size);
        rec_data_size = (uint32_t)compressed_data_size;
    }
    uint32_t compressed_rec_size = rec_data_size + qv_offset;

    if (compressed_rec_size == qv_offset) {
        char dt[DT_LOG_SIZE];
        fprintf(stderr, "%s ERROR [RS_IDX=%015lu] Cannot compress record\n", curr_dt(dt), t_handler->cid);
        finish_thread(r_info, 37, true, t_handler);
    } else if (compressed_rec_size != msg_cli->msg_size) {
        buff[ZIP_INFO_RECORD_OFFSET] |= 0x01;
        msg_cli->zip_info = 1;
        msg_cli->msg_size = compressed_rec_size;
        memcpy(buff, &msg_cli->msg_size, INT_SIZE);
    }
    return compressed_rec_size;
}


bool prepare_append_compaction_dirty_map(region_info_t *r_info, uint32_t block, uint64_t cid) {
    uint32_t segment = block / APPEND_COMPACTION_BLOCKS_PER_SEGMENT;
    uint32_t required_size = segment / 8U + 1U;

    if (required_size <= r_info->append_compact_dirty_map_size)
        return true;
    uint32_t new_size = ((required_size + 63U) / 64U) * 64U;
    uint8_t *new_map = realloc(r_info->append_compact_dirty_map, new_size);

    if (new_map == NULL) {
        char dt[DT_LOG_SIZE];
        fprintf(stderr, "%s ERROR [RS_IDX=%015lu] Failed resize append compaction map for %s from %u to %u bytes\n", curr_dt(dt), cid, r_info->uuid,
                r_info->append_compact_dirty_map_size, new_size);
        return false;
    }
    memset(new_map + r_info->append_compact_dirty_map_size, 0, new_size - r_info->append_compact_dirty_map_size);
    r_info->append_compact_dirty_map = new_map;
    r_info->append_compact_dirty_map_size = new_size;
    return true;
}


void mark_append_compaction_segment(region_info_t *r_info, uint32_t block, uint64_t garbage_bytes, uint8_t bs) {
    uint32_t segment = block / APPEND_COMPACTION_BLOCKS_PER_SEGMENT;
    uint32_t byte = segment / 8U;
    uint8_t mask = (uint8_t)(1U << (segment & 7U));

    if ((r_info->append_compact_dirty_map[byte] & mask) == 0) {
        r_info->append_compact_dirty_map[byte] |= mask;
        r_info->append_compact_dirty_segments++;
    }

    if (UINT64_MAX - r_info->append_compact_garbage_bytes < garbage_bytes)
        r_info->append_compact_garbage_bytes = UINT64_MAX;
    else
        r_info->append_compact_garbage_bytes += garbage_bytes;
    atomic_fetch_add(&append_compact_metric_garbage_generated_bytes, garbage_bytes);
    uint64_t current_ms = (uint64_t)getCurrentTimeMs();

    if (current_ms >= atomic_load(&r_info->append_compaction_retry_after_ms) && get_append_compaction_budget(r_info, bs) != 0 &&
        !atomic_exchange(&r_info->append_compaction_requested, true))
        atomic_store(&r_info->append_compaction_requested_since_ms, current_ms);
}

bool mark_append_compaction_free_space(region_info_t *r_info, uint32_t first_block, uint32_t end_block, uint8_t bs, uint64_t cid) {
    if (!APPEND_COMPACTION_ENABLED || r_info == NULL || r_info->r_idx_b == NULL || bs > BLOCK_ARRAY_LAST_POS || r_info->r_idx_b[bs] == NULL)
        return true;
    idx_region_info_t *idx = r_info->r_idx_b[bs];

    if (idx->fd[FBP] != r_info->data_000_fd || idx->block_size != FIX_BLOCK_SIZE || r_info->enable_block_compression != BLOCK_COMPRESSION_NONE || idx->idx == NULL ||
        idx->idx[FBP] == NULL)
        return true;

    if (end_block > idx->b_offset[FBP])
        end_block = idx->b_offset[FBP];

    if (end_block > idx->f_idx_size[FBP])
        end_block = idx->f_idx_size[FBP];

    if (first_block == 0)
        first_block = 1;

    for (uint32_t block = first_block; block < end_block; block++) {
        if (idx->idx[FBP][block].z_index >= idx->block_size_zip)
            continue;

        if (!prepare_append_compaction_dirty_map(r_info, block, cid))
            return false;
        mark_append_compaction_segment(r_info, block, 0, bs);
    }
    return true;
}

void account_append_compaction_block_change(region_info_t *r_info, uint8_t b, uint8_t bs, uint32_t block, uint32_t old_z_index, uint64_t cid) {
    idx_region_info_t *idx = r_info->r_idx_b[bs];

    if (b != FBP || block == 0 || idx->fd[b] != r_info->data_000_fd || idx->block_size != FIX_BLOCK_SIZE || r_info->enable_block_compression != BLOCK_COMPRESSION_NONE)
        return;
    uint32_t new_z_index = idx->idx[b][block].z_index;

    if (new_z_index >= old_z_index) {
        uint64_t added = (uint64_t)(new_z_index - old_z_index) * idx->bsize_factor;

        if (UINT64_MAX - r_info->append_compact_occupied_bytes < added)
            r_info->append_compact_occupied_bytes = UINT64_MAX;
        else
            r_info->append_compact_occupied_bytes += added;
    } else {
        uint64_t removed = (uint64_t)(old_z_index - new_z_index) * idx->bsize_factor;
        r_info->append_compact_occupied_bytes = r_info->append_compact_occupied_bytes > removed ? r_info->append_compact_occupied_bytes - removed : 0;
        (void)mark_append_compaction_free_space(r_info, block, block + 1U, bs, cid);
    }
}

void remove_coll(struct region_info_t *r_info, uint8_t b, uint32_t coll_pos, uint8_t bs) {
    uint32_t last_coll_pos = (r_info->r_idx_b[bs]->coll_count_curr[b] - 1) * (uint32_t)COLL_KEEPER_SIZE;
    memcpy(r_info->r_idx_b[bs]->coll_keeper[b] + coll_pos, r_info->r_idx_b[bs]->coll_keeper[b] + last_coll_pos, (uint32_t)COLL_KEEPER_SIZE);
    memset(r_info->r_idx_b[bs]->coll_keeper[b] + last_coll_pos, 1, (uint32_t)COLL_KEEPER_SIZE);
    r_info->r_idx_b[bs]->coll_count_curr[b]--;
}

